def 金额写法():
    v = rnd.choice([3, 5, 8, 12, 15.5, 20, 35, 60, 120])
    r = rnd.random()
    if r < 0.3:
        return f"{v}万" if v != int(v) else f"{int(v)}万"
    if r < 0.45:
        return f"¥{int(v * 10000):,}"
    if r < 0.55:
        return f"{v}万元"
    return int(v * 10000)

def 日期写法(d):
    r = rnd.random()
    if r < 0.4:
        return d  # Excel 日期格子
    if r < 0.65:
        return d.strftime("%Y/%m/%d")
    if r < 0.85:
        return d.strftime("%Y-%m-%d")
    return f"{d.year}年{d.month}月{d.day}日"

