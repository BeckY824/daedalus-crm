/**
 * 侧栏底部那条 AI 任务：**一条完成通知，不是一张单子**（2026-09-19 改）。
 *
 * 原来那版是左下角一个方块列表，最多四行，答完了还得人点一下才消失——
 * 于是它一直占着地方，而人想知道的只有「我刚问那句，答完了没有」。
 * 现在一次只显示一条，答完的自己走；人切去别的应用了，由桌面端发系统通知叫他。
 *
 * 这里钉三件规矩：挑哪一条、谁会自己走、叫人的时候说什么。
 * 这三件写进 JSX 就只能靠眼睛看，破了不会有人发现——界面照样能用。
 */
import { describe, it, expect } from "vitest";
import { 挑一条, 类名, 该自动消, 通知文案, 自动消毫秒, type 快照项 } from "@/lib/ai-task-bar";

const 项 = (key: string, status: 快照项["status"], 名: string, 有建议 = false, 去?: string): 快照项 => ({
  key,
  status,
  标签: { 名, 去 },
  有建议,
});

describe("一次只显示一条，挑哪一条", () => {
  it("一条都没有就什么都不画", () => {
    expect(挑一条([])).toBeNull();
  });

  it("还在跑的最要紧——人正在等它", () => {
    const 条 = 挑一条([项("a", "done", "答完的"), 项("b", "loading", "跑着的")])!;
    expect(条.名).toBe("跑着的");
    expect(条.态).toBe("跑着");
    expect(条.说明).toBe("正在想…");
  });

  it("没有在跑的，先说失败——那是要人知道的", () => {
    const 条 = 挑一条([项("a", "done", "答完的"), 项("b", "error", "没答上来的")])!;
    expect(条.态).toBe("失败");
    expect(条.名).toBe("没答上来的");
  });

  it("答完但带着建议卡的，排在单纯答完的前面：它在等人点确认", () => {
    const 条 = 挑一条([项("a", "done", "只是答完"), 项("b", "done", "记一笔", true)])!;
    expect(条.态).toBe("待确认");
    expect(条.说明).toBe("等你确认");
  });

  it("同时好几条就缀一个 +N，不把左下角铺成收件箱", () => {
    const 条 = 挑一条([项("a", "loading", "一"), 项("b", "loading", "二"), 项("c", "loading", "三")])!;
    expect(条.名).toBe("一");
    expect(条.还有).toBe(2);
  });

  it("只有一条时不缀 +N", () => {
    expect(挑一条([项("a", "loading", "一")])!.还有).toBe(0);
  });

  it("点了回哪儿照抄标签——面板里问的那些没有「去」，组件据此不画成链接", () => {
    expect(挑一条([项("a", "loading", "首页问的", false, "/dashboard#turn-1")])!.去).toBe("/dashboard#turn-1");
    expect(挑一条([项("a", "loading", "面板里问的")])!.去).toBeUndefined();
  });

  it("四种态各有一个样式表认得的类名", () => {
    expect(类名).toEqual({ 跑着: "loading", 失败: "error", 待确认: "wait", 答完: "done" });
  });
});

/**
 * 「答完了自己走」是这次改版的全部意思。
 * 但要人做事的那两种不能走——自己淡掉就等于把一件没做完的事悄悄抹了。
 */
describe("谁会自己走", () => {
  it("单纯答完的，3 秒后自己走", () => {
    expect(该自动消(项("a", "done", "答完了"))).toBe(true);
    expect(自动消毫秒).toBe(3000);
  });

  it("还在跑的不走——那条正是用来说「它还没完」的", () => {
    expect(该自动消(项("a", "loading", "跑着"))).toBe(false);
  });

  it("失败的不走：人得知道它没答上来", () => {
    expect(该自动消(项("a", "error", "失败了"))).toBe(false);
  });

  it("等人确认的不走：那张建议卡还没人点", () => {
    expect(该自动消(项("a", "done", "记一笔", true))).toBe(false);
  });
});

/**
 * 人切去别的应用了，侧栏那条进度就等于不存在。桌面端这时候叫一声。
 * 弹不弹（窗口在不在前台）由壳判断，见 desktop/main.js 的 notify:show。
 */
describe("叫人的时候说什么", () => {
  it("还在跑就没什么可说的", () => {
    expect(通知文案(项("a", "loading", "跑着"))).toBeNull();
  });

  it("答完了：标题一句话，正文是问的那句", () => {
    expect(通知文案(项("a", "done", "张悦还能怎么推进"))).toEqual({ 标题: "答完了", 正文: "张悦还能怎么推进" });
  });

  it("带建议卡的说清楚还要人点一下，别让人以为完事了", () => {
    expect(通知文案(项("a", "done", "记一笔", true))!.标题).toBe("答完了，有一条等你确认");
  });

  it("失败也叫一声——不叫的话人会一直等一个永远不来的答案", () => {
    expect(通知文案(项("a", "error", "查一下"))).toEqual({ 标题: "没答上来", 正文: "查一下" });
  });
});
