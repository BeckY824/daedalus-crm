/**
 * 通用查询的受限规格。
 *
 * **这是全系统第二危险的逻辑**（第一是推荐归属）：它的失败模式不是「答不出来」，
 * 是「查错了还很自信地报个数」——不报错、不白屏，只是那个数是错的，
 * 而回答里不会有任何迹象。所以这一组用例钉三件事：
 *
 *   1. 白名单之外的东西一律进不来（表、字段、运算、关联、枚举取值）
 *   2. 拼错的枚举值要**当场报错**，不能当普通字符串查下去查出 0 条
 *   3. `说人话()` 必须把它真正查的东西原样说出来——过程条上人要能核对
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { 校验规格, 说人话, 编译, 表们, 关联们, 取数上限 } from "@/lib/agent/query";

const 查 = (raw: unknown) => 校验规格(raw);
const 挂 = (raw: unknown) => () => 校验规格(raw);

describe("白名单之外一律进不来", () => {
  it("表不在白名单：拒绝，并把能查的列出来", () => {
    expect(挂({ 表: "User" })).toThrow(/没有「User」这张表/);
    expect(挂({ 表: "AiMessage" })).toThrow(/能查的/);
    expect(挂({ 表: "" })).toThrow();
    expect(挂({})).toThrow();
  });

  it("字段不在白名单：拒绝，并把能用的列出来", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "password", 运算: "等于", 值: "x" }] })).toThrow(/没有「password」这个字段/);
    // id 类外键刻意没开：跨表走「关联」，不靠人肉拼 id
    expect(挂({ 表: "客户", 条件: [{ 字段: "salesOwnerId", 运算: "等于", 值: "x" }] })).toThrow(/没有.*这个字段/);
  });

  it("运算符不认识、或用在不合适的类型上，都拒绝", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "姓名", 运算: "正则", 值: ".*" }] })).toThrow(/不认识的运算/);
    // 姓名是文本，不能「大于」
    expect(挂({ 表: "客户", 条件: [{ 字段: "姓名", 运算: "大于", 值: 1 }] })).toThrow(/是文本，不能用「大于」/);
    // 金额是数字，不能「包含」
    expect(挂({ 表: "商机", 条件: [{ 字段: "金额", 运算: "包含", 值: "1" }] })).toThrow(/不能用「包含」/);
  });

  it("排序键也必须在白名单里", () => {
    expect(挂({ 表: "客户", 排序: { 字段: "password", 降序: true } })).toThrow(/没有.*这个字段/);
  });

  it("关联只走白名单里那几条，方向也认", () => {
    expect(挂({ 表: "客户", 关联: { 路径: "客户.销售负责人", 条件: [{ 字段: "姓名", 运算: "等于", 值: "张三" }] } })).toThrow(/没有「客户.销售负责人」这条关联/);
    // 渠道一条出发的关联都没有：路径名不认识时直说「没有可以跨的表」，别让人去猜该填什么
    expect(挂({ 表: "渠道", 关联: { 路径: "渠道.客户", 条件: [] } })).toThrow(/没有可以跨的表/);
    // 路径本身认识、但不是从这张表出发的：报方向，比报「不认识」有用
    expect(挂({ 表: "渠道", 关联: { 路径: "商机.客户", 条件: [] } })).toThrow(/是从「商机」出发的，不是「渠道」/);
    // 走了关联却不给条件 = 白跨一张表
    expect(挂({ 表: "商机", 关联: { 路径: "商机.客户", 条件: [] } })).toThrow(/没给任何条件/);
  });
});

/**
 * 枚举拼错必须当场红。
 *
 * 「跟进状态 = 意向高」（正确的是「意向较高」）如果当普通字符串查下去，
 * 会如实返回 0 条，而模型照着 0 条答「一位都没有」——
 * 这正是「查错了还很自信地报个数」最典型的一种，而且没有任何迹象。
 */
describe("枚举值拼错当场报错，不许悄悄查出 0 条", () => {
  it("跟进状态少一个字就拒绝，并列出全部合法取值", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "跟进状态", 运算: "等于", 值: "意向高" }] }))
      .toThrow(/没有「意向高」这个取值[\s\S]*意向较高/);
  });

  it("商机阶段、线索状态同理", () => {
    expect(挂({ 表: "商机", 条件: [{ 字段: "阶段", 运算: "等于", 值: "报价" }] })).toThrow(/没有「报价」这个取值/);
    expect(挂({ 表: "线索", 条件: [{ 字段: "状态", 运算: "等于", 值: "已成交" }] })).toThrow(/没有「已成交」这个取值/);
  });

  it("「属于」里每一个值都要过枚举这一关", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "跟进状态", 运算: "属于", 值: ["意向较高", "已签约"] }] })).not.toThrow();
    expect(挂({ 表: "客户", 条件: [{ 字段: "跟进状态", 运算: "属于", 值: ["意向较高", "瞎写的"] }] })).toThrow(/瞎写的/);
  });

  it("「包含」是模糊匹配，不走枚举校验——「查状态里带『签约』的」是合理问法", () => {
    expect(挂({ 表: "线索", 条件: [{ 字段: "备注", 运算: "包含", 值: "预算" }] })).not.toThrow();
  });
});

describe("值本身也要校", () => {
  it("日期不合法就报错，不能当成不筛", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "建档时间", 运算: "不早于", 值: "上个月" }] })).toThrow(/要一个能认的日期/);
  });

  it("数字字段给了非数字就报错", () => {
    expect(挂({ 表: "商机", 条件: [{ 字段: "金额", 运算: "大于", 值: "五万" }] })).toThrow(/要一个数/);
  });

  it("「最近 N 天」要在 1~3650 之间", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "最近跟进", 运算: "最近天数", 值: 0 }] })).toThrow(/1~3650/);
    expect(挂({ 表: "客户", 条件: [{ 字段: "最近跟进", 运算: "最近天数", 值: 99999 }] })).toThrow(/1~3650/);
    expect(查({ 表: "客户", 条件: [{ 字段: "最近跟进", 运算: "最近天数", 值: 30 }] }).条件[0].值).toBe(30);
  });

  it("少给值就报错——「跟进状态 是」后面没东西，不能当成不筛然后把全库倒出来", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "跟进状态", 运算: "等于" }] })).toThrow(/少了一个值/);
  });

  it("为空 / 非空不用给值", () => {
    expect(挂({ 表: "客户", 条件: [{ 字段: "预计签约", 运算: "为空" }] })).not.toThrow();
  });
});

describe("取数上限是硬的", () => {
  it("模型要多少都收进上限", () => {
    expect(查({ 表: "客户", 取: 9999 }).取).toBe(取数上限);
    expect(查({ 表: "客户", 取: -5 }).取).toBe(20); // 非法值退回默认
    expect(查({ 表: "客户" }).取).toBe(20);
  });

  it("条件个数也有上限，不许拿一百个条件把 where 撑爆", () => {
    const 一堆 = Array.from({ length: 30 }, () => ({ 字段: "姓名", 运算: "包含", 值: "王" }));
    expect(查({ 表: "客户", 条件: 一堆 }).条件.length).toBe(8);
  });
});

describe("分组", () => {
  it("按枚举分组可以", () => {
    expect(查({ 表: "客户", 分组: "跟进状态" }).分组).toBe("跟进状态");
  });

  it("按日期分组不行——会分出成百上千组", () => {
    expect(挂({ 表: "客户", 分组: "建档时间" })).toThrow(/按它分组会分出成百上千组/);
  });
});

/**
 * 过程条要用的那句话。
 *
 * 这不是装饰：这个工具会「查错了还很自信地报个数」，人必须能一眼核对
 * 「它查的是不是我问的那个东西」。所以这句话必须把**每一个**条件都说出来，
 * 不能省略、不能概括。
 */
describe("说人话：查了什么就写什么", () => {
  it("单表 + 多条件 + 排序 + 取数", () => {
    const s = 查({
      表: "客户",
      条件: [
        { 字段: "跟进状态", 运算: "等于", 值: "意向较高" },
        { 字段: "建档时间", 运算: "不早于", 值: "2026-09-01" },
      ],
      排序: { 字段: "预计签约", 降序: false },
      取: 20,
    });
    expect(说人话(s)).toBe(
      "在客户里，找 跟进状态 是 意向较高、且 建档时间 不早于 2026-09-01，按预计签约时间从小到大排，取 20 条",
    );
  });

  it("跨一张表时，那一跳也要写出来", () => {
    const s = 查({
      表: "签约",
      条件: [{ 字段: "签约日", 运算: "不早于", 值: "2026-09-01" }],
      关联: { 路径: "签约.客户", 条件: [{ 字段: "姓名", 运算: "包含", 值: "陈" }] },
    });
    expect(说人话(s)).toContain("并且所属客户 姓名 包含 陈");
  });

  it("只计数和分组也说清楚", () => {
    expect(说人话(查({ 表: "联系人", 条件: [{ 字段: "关系", 运算: "包含", 值: "母亲" }], 只计数: true })))
      .toBe("在联系人里，找 与学员的关系 包含 母亲，只数个数");
    expect(说人话(查({ 表: "客户", 分组: "跟进状态" }))).toContain("按跟进状态分组数个数");
  });

  it("一个条件都没有时也得说实话：找全部", () => {
    expect(说人话(查({ 表: "渠道" }))).toContain("找全部");
  });

  it("「最近 N 天」写成人看得懂的样子", () => {
    expect(说人话(查({ 表: "客户", 条件: [{ 字段: "最近跟进", 运算: "最近天数", 值: 30 }] })))
      .toContain("最近跟进时间在最近 30 天内");
  });
});

describe("编译成 Prisma", () => {
  it("条件译成 where，排序和 take 带上", () => {
    const r = 编译(查({
      表: "商机",
      条件: [{ 字段: "状态", 运算: "等于", 值: "OPEN" }, { 字段: "金额", 运算: "大于", 值: 50000 }],
      排序: { 字段: "金额", 降序: true },
      取: 10,
    }));
    expect(r.where).toEqual({ AND: [{ status: "OPEN" }, { amount: { gt: 50000 } }] });
    expect(r.orderBy).toEqual({ amount: "desc" });
    expect(r.take).toBe(10);
  });

  it("「不晚于」含当天——和别处的日期区间一个口径", () => {
    const r = 编译(查({ 表: "签约", 条件: [{ 字段: "签约日", 运算: "不晚于", 值: "2026-09-30" }] }));
    const lte = (r.where as { AND: { signedAt: { lte: Date } }[] }).AND[0].signedAt.lte;
    expect(lte.getHours()).toBe(23);
    expect(lte.getDate()).toBe(30);
  });

  it("关联译成嵌套的 is", () => {
    const r = 编译(查({
      表: "客户",
      条件: [],
      关联: { 路径: "客户.来源渠道", 条件: [{ 字段: "名称", 运算: "等于", 值: "小红老师" }] },
    }));
    expect(r.where).toEqual({ AND: [{ channel: { is: { AND: [{ name: "小红老师" }] } } }] });
  });

  it("为空 / 非空译对", () => {
    const r = 编译(查({ 表: "客户", 条件: [{ 字段: "预计签约", 运算: "为空" }] }));
    expect(r.where).toEqual({ AND: [{ expectedSignAt: null }] });
  });
});

/**
 * 白名单的内部一致性。
 *
 * 这是第七份「必须和别处一致的清单」：字段表里的 `列` 必须真的是 Prisma 上的列名，
 * 关联表里的 `从`/`到` 必须真的是表名。写错了不报错——查询照跑，只是永远查不到东西。
 */
describe("白名单自身要自洽", () => {
  it("关联的两头都是白名单里的表", () => {
    for (const [路径, 定义] of Object.entries(关联们)) {
      expect(表们[定义.从], `${路径} 的「从」不是白名单里的表`).toBeDefined();
      expect(表们[定义.到], `${路径} 的「到」不是白名单里的表`).toBeDefined();
      // 路径名要以「从」开头，否则 校验规格 里那句「是从 X 出发的」会自相矛盾
      expect(路径.startsWith(`${定义.从}.`), `${路径} 的名字该以「${定义.从}.」开头`).toBe(true);
    }
  });

  it("每张表至少有一个字段，且列名不重复", () => {
    for (const [名, 表] of Object.entries(表们)) {
      const 列 = Object.values(表.字段).map((f) => (f as { 列: string }).列);
      expect(列.length, `${名} 一个字段都没有`).toBeGreaterThan(0);
      expect(new Set(列).size, `${名} 里有重复的列名`).toBe(列.length);
    }
  });

  it("枚举字段都给了取值——不给的话拼错一个字就会悄悄查出 0 条", () => {
    for (const [名, 表] of Object.entries(表们)) {
      for (const [键, f] of Object.entries(表.字段)) {
        const 字段 = f as { 型: string; 取值?: readonly string[] };
        if (字段.型 === "枚举") {
          expect(字段.取值?.length, `${名}.${键} 是枚举却没给取值`).toBeGreaterThan(0);
        }
      }
    }
  });
});

/**
 * **白名单里的列名必须真的在 Prisma schema 上。**
 *
 * 这是这份清单最要命的一头，也是第七份「必须和别处一致的清单」：
 * 写错一个列名（`followStatus` 打成 `followstatus`），校验这一关照过，
 * 一路到 Prisma 才炸——而那时错误信息是英文的、给模型看的，
 * 用户在过程条上只会看到「工具出错」。schema 改名更糟：这边一个字不动，
 * 静悄悄地就对不上了。所以直接对着 schema 文件核一遍。
 */
describe("白名单的列名和 Prisma schema 对得上", () => {
  const schema = readFileSync(new URL("../prisma/schema.prisma", import.meta.url), "utf8");

  /** 从 schema 里抠出某个 model 的字段名 */
  const 模型字段 = (模型: string): Set<string> => {
    const m = new RegExp(`^model\\s+${模型}\\s*\\{([\\s\\S]*?)^\\}`, "m").exec(schema);
    if (!m) return new Set();
    return new Set(
      m[1]
        .split("\n")
        .map((l) => l.trim())
        .filter((l) => l && !l.startsWith("//") && !l.startsWith("@@") && !l.startsWith("///"))
        .map((l) => l.split(/\s+/)[0]),
    );
  };

  /** 表们 里的 `模型` 是 Prisma client 上的属性名（小驼峰），schema 里的 model 名是大驼峰 */
  const 大驼峰 = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

  it("每张表的 model 名在 schema 里存在", () => {
    for (const [名, 表] of Object.entries(表们)) {
      const 字段 = 模型字段(大驼峰(表.模型));
      expect(字段.size, `schema 里找不到 model ${大驼峰(表.模型)}（白名单的「${名}」指向它）`).toBeGreaterThan(0);
    }
  });

  it("每个字段的列名在对应 model 上存在", () => {
    const 漏了: string[] = [];
    for (const [名, 表] of Object.entries(表们)) {
      const 有 = 模型字段(大驼峰(表.模型));
      for (const [键, f] of Object.entries(表.字段)) {
        const 列 = (f as { 列: string }).列;
        if (!有.has(列)) 漏了.push(`${名}.${键} → ${大驼峰(表.模型)}.${列}`);
      }
    }
    expect(漏了, `这些列名在 schema 上不存在：\n${漏了.join("\n")}`).toEqual([]);
  });

  it("每条关联的关系字段在出发那张表上存在", () => {
    const 漏了: string[] = [];
    for (const [路径, 定义] of Object.entries(关联们)) {
      const 有 = 模型字段(大驼峰(表们[定义.从].模型));
      if (!有.has(定义.列)) 漏了.push(`${路径} → ${大驼峰(表们[定义.从].模型)}.${定义.列}`);
    }
    expect(漏了, `这些关系字段在 schema 上不存在：\n${漏了.join("\n")}`).toEqual([]);
  });
});
