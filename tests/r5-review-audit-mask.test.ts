/**
 * 第五轮对抗复查 · 共享试用区操作日志打码（e106bd8 的 文字里号码打码）
 *
 * 留痕里有两种号码：
 *   1. 客户「电话」那一格改动的原值 / 新值——库里存的规整后的样子。像手机号 收 6–20 位任何数字，
 *      所以没带区号的本地座机「62345678」、不带 + 的海外号、400 电话都是合法的「电话」，打码一个都不认
 *   2. 跟进内容（明细里「内容」前 120 字）、备注改动——人手打的原文，写法什么样都有：
 *      「138  0000  1111」「(010)6234-5678」「010-6234-5678」、全角数字……
 * 红的保持红，等修。
 */
import { describe, it, expect } from "vitest";
import { 文字里号码打码 } from "@/lib/utils";
import { describeCustomerChanges } from "@/lib/audit";
import { 规整手机号, 像手机号 } from "@/lib/phone";

/** 打完码以后还剩几位连着的数字（忽略分隔符）。7 位以上就算号码漏出去了 */
const 漏了 = (s: string) => /\d(?:[\s\-().（）]*\d){6,}/.test(s.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0)));

describe("「电话」那一格的改动：库里存的就是规整后的样子", () => {
  it.each([
    ["没带区号的本地座机", "6234 5678"],
    ["香港号（不带 +852）", "9123 4567"],
    ["不带 + 的美国号", "415-555-0132"],
    ["400 电话", "400-800-1234"],
  ])("%s：规整后是合法电话，进了留痕没打码", (_, 原) => {
    const 存的 = 规整手机号(原);
    expect(像手机号(存的), `${原} → ${存的}`).toBe(true);
    const detail = JSON.stringify(describeCustomerChanges(["phone"], { phone: "13800001111" }, { phone: 存的 }));
    const 打完 = 文字里号码打码(detail);
    expect(漏了(打完), 打完).toBe(false);
  });
});

describe("跟进内容 / 备注里人手打的号码", () => {
  it.each([
    ["分组间两个空格", "客户换号了，新号 138  0000  1111"],
    ["4-3-4 分组", "手机 1380-000-1111"],
    ["括号区号", "座机 (010)62345678"],
    ["区号后再分两段", "座机 010-6234-5678"],
    ["全角数字", "电话：１３８００００１１１１"],
    ["点分隔", "电话 138.0000.1111"],
  ])("%s", (_, 原) => {
    const detail = JSON.stringify({ 客户: "王同学", 类型: "电话", 状态: "已完成", 内容: 原 });
    const 打完 = 文字里号码打码(detail);
    expect(漏了(打完), 打完).toBe(false);
    expect(() => JSON.parse(打完)).not.toThrow();
  });
});
