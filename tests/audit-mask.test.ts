/**
 * 共享试用区的操作日志里，号码出库前打码（2026-10-01 排查 A5）。
 * 钉住两头：像电话的都打掉；日期、金额、id 不误伤，明细的 JSON 打完还解得开。
 */
import { describe, it, expect } from "vitest";
import { 文字里号码打码 } from "@/lib/utils";

describe("文字里号码打码", () => {
  it.each([
    ["新建客户 王建国（13800001111）", "新建客户 王建国（138****1111）"],
    ["电话 138-0000-1111 → 139 0000 2222", "电话 138****1111 → 139****2222"],
    ["+86 13800001111", "138****1111"],
    ["座机 010-12345678", "座机 010****5678"],
    ["海外 +1 415 555 0132", "海外 141****0132"],
  ])("%s", (原, 该是) => {
    expect(文字里号码打码(原)).toBe(该是);
    expect(文字里号码打码(原)).not.toMatch(/\d{7,}/);
  });

  it("日期、金额、id 不动", () => {
    const s = "2026-10-02 签约 ¥12000000，客户 cmg1a2b3c4d5e6，金额 13800000";
    expect(文字里号码打码(s)).toBe(s);
  });

  it("明细是 JSON：打完还解得开，号码那格打了码", () => {
    const detail = JSON.stringify({ phone: { from: "13800001111", to: "13900002222" }, amount: 12000000, at: "2026-10-02" });
    const 打完 = JSON.parse(文字里号码打码(detail));
    expect(打完).toEqual({ phone: { from: "138****1111", to: "139****2222" }, amount: 12000000, at: "2026-10-02" });
  });
});
