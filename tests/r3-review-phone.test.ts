/**
 * 第三轮对抗复查 · 手机号规整重写（cfdfb96、4e573c1）
 *
 * 老实现原样放在 tests/r3-review-fixtures/phone-dabc4dc.ts（git show dabc4dc:src/lib/phone.ts），逐条对跑。
 *   一、原来就认、现在也必须认（同一个结果）——全绿，钉住
 *   二、重写后变了的：海外号带字丢了「+」、ext / x 分机整格被拒、老库里存的号和新规整对不上
 */
import { describe, it, expect } from "vitest";
import * as 新 from "@/lib/phone";
import { 号键 } from "@/lib/phone";
import * as 老 from "./r3-review-fixtures/phone-dabc4dc";

const 原来就认 = [
  "13800001111", "+86 138 0000 1111", "+86-138-0000-1111", "86-13800001111", "0086 13800001111",
  "138 0000 1111", "138-0000-1111", "(010) 1234 5678", "（010）12345678", "010-12345678", "0755-8888 9999",
  "400-820-8820", "400 820 8820", "+1 (415) 555-0132", "+1 415 555 0132", "+852 9123 4567", "+852-9123-4567",
  "+44 20 7946 0958", "13800001111（微信同号）", "13800001111 微信同号", "手机:13800001111", "Tel: 13800001111",
  "13800001111.0", "'13800001111", "１３８００００１１１１", "+852 9123 4567 (WhatsApp)", "13800001111/13900002222",
  "+65 9123 4567 微信", "+44 7911 123456 whatsapp", "+61 4 1234 5678 手机",
];

describe("一、原来就认的写法，重写后结果不变", () => {
  for (const s of 原来就认) {
    it(JSON.stringify(s), () => {
      const a = 老.规整手机号(s);
      const b = 新.规整手机号(s);
      expect(b).toBe(a);
      expect(新.像手机号(b)).toBe(老.像手机号(a));
    });
  }
  it("打码号码 139****1234 照旧不当号码（规整、像手机号、查电话三处）", () => {
    expect(新.像手机号(新.规整手机号("139****1234"))).toBe(false);
    expect(新.查电话("139****1234", { 必填: true }).ok).toBe(false);
  });
});

describe("二、重写后变坏的", () => {
  /*
    新加的「有大陆手机号就取它」：/(?:\+?0*86)?(1[3-9]\d{9})(?!\d)/ 没有左边界。
    北美号 +1 + 3–9 开头的区号，正好是「1[3-9] + 9 位」，带一点字就被当成大陆手机号、+ 被丢掉
  */
  it.each([
    ["+1 415 555 0132 (cell)", "+14155550132"],
    ["+1 315 555 0123 mobile", "+13155550123"],
    ["+1 (617) 555-0199 office", "+16175550199"],
  ])("海外号带着字 %s：该是 %s（老实现就是），现在丢了 + 成了一个「大陆手机号」", (原, 该是) => {
    expect(老.规整手机号(原)).toBe(该是);
    expect(新.规整手机号(原)).toBe(该是);
  });

  it("同一个美国客户，一次写「+1 415 555 0132」、一次写「+1 415 555 0132 (cell)」：查重认不出是同一个人", () => {
    expect(新.规整手机号("+1 415 555 0132 (cell)")).toBe(新.规整手机号("+1 415 555 0132"));
  });

  /*
    「号码中间夹着字母就不猜」那条（\d[A-Za-z]+\d）先于分机那条判断，把 ext / x 分机也当成打错的号拦下。
    分机正则里明明写了 ext，走不到。老实现收成主号
  */
  it.each(["+1 415 555 0132 ext 12", "+1 415-555-0132 x12", "010-12345678 ext. 801"])(
    "英文分机写法 %s：原来收成主号，现在整格「不像号码」，导入拦行、表单存不了",
    (原) => {
      expect(老.像手机号(老.规整手机号(原))).toBe(true);
      expect(新.查电话(原, { 必填: true }).ok, JSON.stringify(新.查电话(原, { 必填: true }))).toBe(true);
    },
  );

  /*
    规整规则变了，库里没有一起迁：查重是拿规整后的值跟库里存的值精确比对（checkDuplicate / saveCustomer / 导入）。
    老版本把「01012345678转801」存成 01012345678，新版本规整成「01012345678转801」——
    同一张表再导一次，这个人被当成新人再建一份
  */
  // 修法：号码里照旧留着分机（第二轮定的），查重时主号也认（同号写法）——五处查重都按它查
  it("老版本导入过「01012345678转801」（库里存 01012345678）：新版本再导同一格，查重认得出", () => {
    const 库里 = 老.规整手机号("01012345678转801");
    expect(库里).toBe("01012345678");
    expect(新.同号写法(新.规整手机号("01012345678转801"))).toContain(库里);
    expect(新.同号写法("13800001111")).toEqual(["13800001111"]);
  });
});

/*
  回归核对 R-067：分机那类已钉（上面）。这里补 QQ 号和全角横杠——老版本存下来的值，新版本再导同一格时查重认不认得出
*/
describe("R-067 老库里的 QQ 号 / 全角横杠", () => {
  it("QQ 号（带不带「QQ」字样、9 位 10 位）：老实现存的和新实现查重用的是同一个值", () => {
    for (const 格 of ["QQ 123456789", "QQ:123456789", "QQ12345678", "123456789", "1234567890"]) {
      const 库里 = 老.规整手机号(格);
      expect(新.同号写法(新.规整手机号(格)), 格).toContain(库里);
    }
  });

  /*
    全角横杠：老实现把「138－0000－1111」原样存着，把「010－12345678」规整成 12345678（区号丢了）；
    新实现都规整对了（13800001111 / 01012345678）。2026-10-04 修（R-067 / R-069）：查重把库里的值也算成号键
    （去掉分隔符）再比，第一种认得出。第二种**故意不认**：拿 12345678 去认 01012345678 等于去区号模糊匹配，
    会把别的城市同号座机也认成一个人。DB 那一侧的用例在 tests/r067-phone-key.test.ts
  */
  it("R-067 全角横杠的老值：新版本再导同一格，号键对得上；丢了区号的老值不硬认", () => {
    const 库里 = 老.规整手机号("138－0000－1111");
    expect(库里).toBe("138－0000－1111");
    expect(号键(新.规整手机号("138－0000－1111"))).toBe(号键(库里));
    const 丢区号 = 老.规整手机号("010－12345678");
    expect(号键(新.规整手机号("010－12345678"))).not.toBe(号键(丢区号));
  });
});
