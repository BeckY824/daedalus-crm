/**
 * 答不上来的那一次，不能是死胡同。
 *
 * 单人桌面端一天只有 3 次免费提问。一句「没查到，你给个更完整的姓名我再查一次」
 * 当场吃掉三分之一，而人只剩「再问一次、再烧一次」这一条路。
 *
 * 这一组钉两件事，方向相反：
 *   1. 该出现的时候要出现（没查到 / 一个工具都没调）
 *   2. **不该出现的时候一次都不许出现**——正常回答底下挂一条「没查到？」
 *      比没有这条路更伤，人会以为它没答对
 */
import { describe, it, expect } from "vitest";
import { 认死胡同, 摘要搜的词 } from "@/lib/ask-dead-end";

describe("认死胡同", () => {
  it("说了「没找到」就是没答上来，给一条去搜库的路", () => {
    const r = 认死胡同("没有找到「明杰哥」这个人，客户库里查不到匹配的记录。", "明杰哥的电话是多少?", 1);
    expect(r).toEqual({ 词: "明杰哥" });
  });

  it("「你给个更完整的姓名」这种反过来问人的，也算没答上来", () => {
    expect(认死胡同("你给个更完整的姓名或公司名，我再查一次。", "明杰哥的电话是多少?", 2)).toEqual({ 词: "明杰哥" });
  });

  it("一个工具都没调就答的，不管说了什么都算", () => {
    // 这是最伤的一种：它没查就下结论，而人分辨不出哪句是查过的
    expect(认死胡同("你名下目前还没有登记任何渠道。", "明杰哥的电话是多少?", 0)).toEqual({ 词: "明杰哥" });
  });

  it("查过、也答上来了，一次都不许出现", () => {
    expect(认死胡同("李老师的电话是 13900008888。他在系统里登记的是渠道。", "李老师的电话是多少?", 1)).toBeNull();
  });

  it("还没开始答（空回答）不算", () => {
    expect(认死胡同("", "明杰哥的电话是多少?", 0)).toBeNull();
  });

  it("摘不出要搜的词就不给这条路——送人去搜「的」比不给更糟", () => {
    expect(认死胡同("没找到相关记录。", "这个月的情况怎么样", 1)).toBeNull();
    expect(认死胡同("没找到。", "哪些商机可能延期？", 0)).toBeNull();
  });
});

describe("摘要搜的词", () => {
  it("几种把名字摆在明面上的句式都认", () => {
    expect(摘要搜的词("明杰哥的电话是多少?")).toBe("明杰哥");
    expect(摘要搜的词("李老师电话")).toBe("李老师");
    expect(摘要搜的词("王强的联系方式")).toBe("王强");
    expect(摘要搜的词("张三是谁")).toBe("张三");
    expect(摘要搜的词("查一下赵敏的资料")).toBe("赵敏");
  });

  it("写入类的句子一个字都不许摘——那是建议卡的活", () => {
    expect(摘要搜的词("帮我记一笔今天和李四的电话")).toBe("");
    expect(摘要搜的词("把李老师的电话改成 139")).toBe("");
  });

  it("一个字的名字不摘：搜「李」等于把整本库倒出来", () => {
    expect(摘要搜的词("李的电话是多少?")).toBe("");
  });

  it("不是问人的句子不摘", () => {
    expect(摘要搜的词("这个月谁签得最多")).toBe("");
    expect(摘要搜的词("今天该跟谁")).toBe("");
  });
});
