/**
 * 意图直连：固定的问题不问模型。
 *
 * 用户那句话是对的——业务逻辑和字段是固定的，不该每次让模型重新推理一遍。
 * 这张表把「这类问题 → 这条查询」钉死：命中就直接跑，省掉一次决策往返，
 * 同一句话永远走同一条路。
 *
 * **这组用例的重点不是「命中了多少」，是「不该命中的一条都没命中」。**
 * 漏了只是慢一点（落回 agent 循环），错了是答非所问。
 */
