/**
 * 「粘任何东西」那一步里**不靠模型的那一半**。
 *
 * 提示词写得再好也只是请求，模型照不照做是另一回事。这一组钉的就是
 * 「模型没照做时会发生什么」，四件事：
 *
 *   1. 编出来的格子要被抓住并清空——假客户进了库，看不出来，还会被打电话
 *   2. 原文里有、表里没有的手机号要报出来——漏人是最安静的一种错
 *   3. 抄写走样（空格、横线、全角）不许当成编造——误报会让人学会忽略这条提示
 *   4. 形状不对、超限、空表都要有个说法，不能往下游漏
 *
 * 第 1 条和第 2 条是一对反方向的错，缺一条这套核对就有一半是瞎的。
 */
import { describe, it, expect } from "vitest";
import { 核对, 规整比对, 抽手机号, 组提示词, 粘贴行数上限, 单格上限 } from "@/lib/import/paste";
import { 列数上限 } from "@/lib/import/parse";

const 原文 = [
  "今天群里接龙的：",
  "1. 王强 13800001111 远山资本，下周三再聊",
  "2. 李娜，手机 138-0000-2222，平川科技，已经加了微信",
  "3. 赵敏 138 0000 3333 长河教育",
].join("\n");

const 表 = (数据: string[][], 表头 = ["姓名", "手机号", "公司"]) => ({ 表头, 数据 });

describe("编出来的格子", () => {
  it("原文里没有的手机号要被抓住并清空", () => {
    const r = 核对(表([["王强", "13900009999", "远山资本"]]), 原文);
    expect(r.编造).toHaveLength(1);
    expect(r.编造[0]).toMatchObject({ 行号: 2, 列名: "手机号", 值: "13900009999" });
    // 清空，不是留着标记：留着的话下一步「对列」之后它照样进库
    expect(r.数据[0][1]).toBe("");
  });

  it("原文里没有的人整行会空掉，于是这一行自然进不了库", () => {
    // 摊开() 里那条「没有手机号的行进不来」接着会把它挡下，这里只确认格子被清干净
    const r = 核对(表([["周不存在", "13700007777", "某公司"]]), 原文);
    expect(r.编造).toHaveLength(3);
    expect(r.数据).toHaveLength(0);
  });

  it("表头不参与核对——原文压根没有表头是常态", () => {
    const r = 核对(表([["王强", "13800001111", "远山资本"]], ["姓名", "手机号", "公司"]), 原文);
    expect(r.编造).toHaveLength(0);
  });
});

describe("抄写走样不算编造", () => {
  it("空格、横线、全角数字都要认得出是同一个号", () => {
    for (const 号 of ["13800001111", "138 0000 1111", "138-0000-1111", "１３８００００１１１１"]) {
      const r = 核对(表([["王强", 号, ""]]), 原文);
      expect(r.编造, `「${号}」被当成编造了`).toHaveLength(0);
    }
  });

  it("原文里写成 138-0000-2222，模型抄成 13800002222 也算数", () => {
    expect(核对(表([["李娜", "13800002222", "平川科技"]]), 原文).编造).toHaveLength(0);
  });

  it("规整比对两边都规整，所以只会更宽松", () => {
    expect(规整比对("（远山）资本 ")).toBe("远山资本");
    expect(规整比对("Ａ-B_c")).toBe("abc");
  });
});

describe("漏掉的人", () => {
  it("原文里的手机号一个都不在表里，要全列出来", () => {
    const r = 核对(表([["王强", "13800001111", "远山资本"]]), 原文);
    expect(r.漏掉).toEqual(["13800002222", "13800003333"]);
  });

  it("三个人都在表里就不报", () => {
    const r = 核对(
      表([
        ["王强", "13800001111", "远山资本"],
        ["李娜", "138-0000-2222", "平川科技"],
        ["赵敏", "138 0000 3333", "长河教育"],
      ]),
      原文,
    );
    expect(r.漏掉).toEqual([]);
  });

  it("只认大陆手机号：身份证号、金额、订单号不算人，否则每次都弹假警报", () => {
    // 假警报比没有警报更糟——人学会了忽略它
    expect(抽手机号("身份证 110101199003072316，合同 42000 元，订单 20260919001")).toEqual([]);
  });

  it("日期挨着号码、中间只有一个空格时，两截都要分得清", () => {
    // 整段抹空格会粘成 2026091913800001111，再去里面找 11 位就开始撞上假号码；
    // 一个空格都不抹又认不出「138 0000 1111」。这条钉的就是这两难
    expect(抽手机号("2026-09-19 13800001111")).toEqual(["13800001111"]);
    expect(抽手机号("+86 138 0000 1111")).toEqual(["13800001111"]);
    expect(抽手机号("13800001111 13800002222")).toEqual(["13800001111", "13800002222"]);
  });

  it("同一个号在原文里出现两次只算一个人", () => {
    expect(抽手机号("王强 13800001111，后来又发了一遍 138 0000 1111")).toEqual(["13800001111"]);
  });
});

describe("模型给的东西一律当不可信输入", () => {
  it("形状不对就抛错，不往下游漏", () => {
    expect(() => 核对({}, 原文)).toThrow(/没有按格式返回/);
    expect(() => 核对({ 表头: "姓名", 数据: [] }, 原文)).toThrow();
    expect(() => 核对({ 表头: [], 数据: [] }, 原文)).toThrow(/读出任何一列/);
  });

  it("行比表头长就截断、短就补空，下游可以假定每行一样长", () => {
    const r = 核对({ 表头: ["姓名", "手机号"], 数据: [["王强", "13800001111", "多出来的"], ["李娜"]] }, 原文);
    expect(r.数据.every((row) => row.length === 2)).toBe(true);
  });

  it("超出行列上限要切掉并说出来，和文件那条路共用同一个提示条", () => {
    const 多行 = Array.from({ length: 粘贴行数上限 + 5 }, () => ["王强", "13800001111"]);
    expect(核对({ 表头: ["姓名", "手机号"], 数据: 多行 }, 原文).截断了?.行).toBe(粘贴行数上限 + 5);
    const 多列 = { 表头: Array.from({ length: 列数上限 + 3 }, () => "姓名"), 数据: [] };
    expect(核对(多列, 原文).截断了?.列).toBe(列数上限 + 3);
  });

  it("单个格子按上限截断——备注列在聊天记录上最容易长成一整段", () => {
    const 长 = "远".repeat(单格上限 + 100);
    const r = 核对({ 表头: ["备注"], 数据: [[长]] }, 长);
    expect(r.数据[0][0]).toHaveLength(单格上限);
    // 截出来的仍然是原文的一截，所以不该被当成编造
    expect(r.编造).toHaveLength(0);
  });

  it("模型把号码当数字返回时也照样核对，不会因为类型不对就放行", () => {
    expect(核对({ 表头: ["手机号"], 数据: [[13800001111]] }, 原文).编造).toHaveLength(0);
    expect(核对({ 表头: ["手机号"], 数据: [[13900009999]] }, 原文).编造).toHaveLength(1);
  });

  it("整行都空的行直接丢掉，不占预览上那几个数", () => {
    expect(核对({ 表头: ["姓名", "手机号"], 数据: [["", ""], ["王强", "13800001111"]] }, 原文).数据).toHaveLength(1);
  });
});

describe("提示词", () => {
  it("列名建议跟着业务配置走，否则猜列一列都对不上", () => {
    const p = 组提示词("随便", ["姓名", "手机号", "公司"], "客户");
    expect(p).toContain("姓名、手机号、公司");
    expect(p).toContain("若干个客户的信息");
  });

  it("原文原样带进提示词，不做任何预处理", () => {
    expect(组提示词(原文, ["姓名"], "学员")).toContain(原文);
  });

  it("那几条硬规矩要写在提示词里：原字、留空、不换算日期", () => {
    const p = 组提示词("x", ["姓名"], "学员");
    expect(p).toContain("原样出现过的字");
    expect(p).toContain("空字符串");
    expect(p).toContain("不要换算成具体哪一天");
  });
});
