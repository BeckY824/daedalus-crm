/**
 * 虚构号段（verify/fiction.ts，10-18 复核）：Ofcom 留给影视剧的号段全表 + 北美 555-0100–0199。
 * 每段两头都在、紧挨着的外面不算；本国写法、国际写法、带 (0) 的都认
 */
import { describe, it, expect } from "vitest";
import { 虚构号段, 是虚构号码 } from "@/lib/research/verify/fiction";

describe("Ofcom 影视剧号段", () => {
  const 段们: [string, string, string][] = [
    ["0113 496 0000", "0113 496 0999", "利兹"],
    ["0114 496 0000", "0114 496 0999", "谢菲尔德"],
    ["0115 496 0000", "0115 496 0999", "诺丁汉"],
    ["0116 496 0000", "0116 496 0999", "莱斯特"],
    ["0117 496 0000", "0117 496 0999", "布里斯托"],
    ["0118 496 0000", "0118 496 0999", "雷丁"],
    ["0121 496 0000", "0121 496 0999", "伯明翰"],
    ["0131 496 0000", "0131 496 0999", "爱丁堡"],
    ["0141 496 0000", "0141 496 0999", "格拉斯哥"],
    ["0151 496 0000", "0151 496 0999", "利物浦"],
    ["0161 496 0000", "0161 496 0999", "曼彻斯特"],
    ["020 7946 0000", "020 7946 0999", "伦敦"],
    ["0191 498 0000", "0191 498 0999", "泰恩赛德"],
    ["028 9649 6000", "028 9649 6999", "北爱尔兰"],
    ["029 2018 0000", "029 2018 0999", "加的夫"],
    ["01632 960000", "01632 960999", "无地区"],
    ["07700 900000", "07700 900999", "手机"],
    ["08081 570000", "08081 570999", "免费电话"],
    ["0909 879 0000", "0909 879 0999", "付费电话"],
    ["03069 990000", "03069 990999", "全国"],
  ];
  it.each(段们)("%s – %s（%s）两头都算", (头, 尾, 名) => {
    for (const x of [头, 尾]) {
      const r = 是虚构号码(x, "GB");
      expect(r).toContain("Ofcom 留给影视剧的虚构号段");
      expect(r).toContain(名);
    }
  });

  it("紧挨着的外面不算；真号不算", () => {
    expect(是虚构号码("020 7946 1000", "GB")).toBeNull();
    expect(是虚构号码("0114 496 1000", "GB")).toBeNull();
    expect(是虚构号码("028 9649 5999", "GB")).toBeNull();
    expect(是虚构号码("028 9649 7000", "GB")).toBeNull();
    expect(是虚构号码("07700 901000", "GB")).toBeNull();
    // Sunrgy 官网上的公司电话
    expect(是虚构号码("+44 114 327 1314")).toBeNull();
    expect(是虚构号码("0114 327 1314", "GB")).toBeNull();
  });

  it("国际写法、带 (0)、连写都认；别的国家同样的数字不算", () => {
    expect(是虚构号码("+44 20 7946 0123")).toContain("伦敦");
    expect(是虚构号码("+44 (0)20 7946 0123")).toContain("伦敦");
    expect(是虚构号码("+442079460123")).toContain("伦敦");
    expect(是虚构号码("+49 20 7946 0123")).toBeNull();
    expect(虚构号段("49", "2079460123")).toBeNull();
    expect(虚构号段("44", "2079460123")).toContain("伦敦");
  });
});

describe("北美 555-0100 到 555-0199", () => {
  it("两头都算，外面不算；没给国家码的不认", () => {
    expect(是虚构号码("+1 415 555 0100")).toContain("555-0100 到 555-0199");
    expect(是虚构号码("+1 (212) 555-0199")).toContain("北美");
    expect(是虚构号码("+1 415 555 0200")).toBeNull();
    expect(是虚构号码("+1 415 555 0099")).toBeNull();
    expect(是虚构号码("415 555 0132")).toBeNull();
    expect(是虚构号码("415 555 0132", "US")).toContain("北美");
  });
});
