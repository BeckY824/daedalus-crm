/**
 * 复查 861a62f 规整手机号「号码带着字只取那一串号码」：取的是**第一串 6 位以上数字**，不是那个电话。
 *   - 「QQ 12345678 / 13800001111」→ 取成 12345678（QQ 号成了查重主键）
 *   - 「010-12345678 转 801」→ 分机号悄悄丢了；表单那条路（saveCustomer / checkDuplicate）不像导入那样把原文并进备注
 *   - 「138O0001111」（字母 O 打错）→ 取成 0001111，一个完全不同的 7 位号，原来是原样留着让人看得出错
 */
import { describe, it, expect } from "vitest";
import { 规整手机号, 查电话 } from "@/lib/phone";

describe("复查：规整手机号取错那一串", () => {
  it("号码前面有别的数字（QQ / 微信号）：应取手机号，不是 QQ 号", () => {
    expect(规整手机号("QQ 12345678 / 13800001111")).toBe("13800001111"); // 实际：12345678
  });
  it("座机带分机：表单存进去的号码不该把分机号悄悄扔掉", () => {
    const r = 查电话("010-12345678 转 801", { 必填: true });
    expect(r.ok && r.phone).toContain("801"); // 实际：01012345678
  });
  it("号码里混了个字母（打错）：不该被截成另一个 7 位号码存下", () => {
    const r = 查电话("138O0001111", { 必填: true });
    expect(r.ok ? r.phone : "拒").not.toBe("0001111"); // 实际：0001111
  });
});
