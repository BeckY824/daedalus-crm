/**
 * 第四轮对抗复查 · 导入认表头（953a7b2：「像表头 = 没有一格含 6 位以上数字」）
 *
 * 红的保持红，等修。
 *   表头上面有一行大标题、表头里又有一格带长串数字（日期列名「20260901」、示例号码「手机号(例:13800001111)」）：
 *   两轮找表头都跳过它，退回第 0 行——大标题成了表头，真表头成了第一位客户。
 *   （没有大标题时退回第 0 行恰好是对的，所以只在「标题 + 这种表头」时出事）
 */
import { describe, it, expect } from "vitest";
import { 成表 } from "@/lib/import/parse";

describe("表头里带长串数字", () => {
  it("大标题 + 表头有一列叫「20260901」（按日期记跟进的表）：表头该是第二行", () => {
    const { 表头, 数据 } = 成表([
      ["2026 年 9 月客户名单"],
      ["姓名", "手机号", "20260901", "20260908"],
      ["张三", "13800000001", "已联系", "未接"],
    ]);
    expect(表头.slice(0, 2), `表头=${表头.join("/")}；第一行数据=${数据[0]?.join("/")}`).toEqual(["姓名", "手机号"]);
  });

  it("大标题 + 表头「手机号（例：13800001111）」（照模板填的表）：表头该是第二行", () => {
    const { 表头, 数据 } = 成表([
      ["客户导入模板"],
      ["姓名", "手机号（例：13800001111）", "备注"],
      ["张三", "13800000001", ""],
      ["李四", "13800000002", "老客户"],
    ]);
    expect(表头[0], `表头=${表头.join("/")}；第一行数据=${数据[0]?.join("/")}`).toBe("姓名");
    expect(数据.map((r) => r[0])).toEqual(["张三", "李四"]);
  });

  it("（绿，钉住）没有大标题时，带日期列名的表头照旧是第一行", () => {
    const { 表头 } = 成表([
      ["姓名", "手机号", "20260901"],
      ["张三", "13800000001", "已联系"],
    ]);
    expect(表头[0]).toBe("姓名");
  });
});
