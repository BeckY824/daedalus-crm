/**
 * 客户电话的规矩：怎么规整、怎样算「像个号码」、什么时候必填。
 *
 * **导入、客户表单、服务端 saveCustomer 三处共用这一份。** 2026-09-28 审查 S2：
 * 导入故意放宽（收海外号、座机），表单却用大陆 11 位手机号的正则，
 * 结果导进来的人以后一编辑就被卡住，外贸用户的海外客户根本建不了。
 * 两处各写一条规矩，迟早有一条落后——所以只留这一处。
 *
 * 纯函数，浏览器和服务端都能用。
 */
import { maskPhone } from "@/lib/utils";

/**
 * 手机号规整：只留数字，去掉国家码和分隔符。
 *
 * 为什么非规整不可：这是认人的那一列。Excel 里同一个号码有十种写法
 * （`138 0000 1111`、`138-0000-1111`、`+86 13800001111`、被存成文本的 `'13800001111'`），
 * 不规整的话同一个人会被当成十个人，而查重是**精确比对**——
 * 一个空格就足以让「跳过重复」这件事整个失效，且毫无迹象。
 * 表单那条路也走这里：人手敲的「138 0000 1111」和导入进来的「13800001111」得是同一个人。
 */
export function 规整手机号(v: string): string {
  let s = v.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0)).trim();
  s = s.replace(/^'/, "");
  // 有的系统导出 CSV 时把号码当数字写成「13800001111.0」：先把这个尾巴去掉，不然点被删后成了 12 位的另一个号（2026-10-02 排查）
  s = s.replace(/^(\+?\d[\d\s\-]*)\.0+$/, "$1");
  s = s.replace(/[\s\-()（）.]/g, "");
  /*
    号码前后带着字（「13800001111（微信同号）」「手机:13800001111」「138 0000 1111/王总」）：只取那一串号码。
    原来原样进库，存成「13800001111微信同号」，下次用干净的号码导入或建档就认不出是同一个人（2026-10-02 排查）。
    带 * 的是打码给人看的样子，不在这里猜，交给 像手机号 / 查电话 去拒。
  */
  if (!s.includes("*") && /[^\d+]/.test(s)) {
    const m = s.match(/\+?\d{6,20}/);
    if (m) s = m[0];
  }
  s = s.replace(/^\+?0*86(?=\d{11}$)/, "");
  return s;
}

/** 规整时有没有丢掉号码以外的字（「微信同号」这种）：导入据此把原文并进备注，一个字都不丢 */
export function 号码带着字(v: string): boolean {
  const 去分隔 = v.replace(/[０-９]/g, "0").replace(/^'/, "").replace(/\.0+$/, "").replace(/[\s\-()（）.+]/g, "");
  return !去分隔.includes("*") && /[^\d]/.test(去分隔) && /\d{6,}/.test(去分隔);
}

/**
 * 看着像个号码吗。
 *
 * **故意不用大陆手机号的正则 `/^1[3-9]\d{9}$/`。** 人手上真有座机、真有带分机号的、
 * 真有海外号码。用大陆手机号去卡，等于告诉人「你这三十个客户不合法」——
 * 而他们明明是他的客户。
 *
 * 只挡两种：根本没有数字（把姓名列当成手机号列对错了），和长得离谱。
 */
export function 像手机号(s: string): boolean {
  // 打了码的（138****1111）不是号码：规整后还剩 7 位数字、长度上过得去，导入会把它当查重主键收下（2026-10-02 排查 X9）
  if (s.includes("*")) return false;
  const 数字 = s.replace(/\D/g, "");
  return 数字.length >= 6 && 数字.length <= 20;
}

/**
 * 表单和 saveCustomer 用的那一句：这个电话能不能存、存成什么。
 *
 * **必填只管新建，和「原来就有号码的」。** 演示数据、线索转过来的、AI 建的档案里
 * 真有没电话的人；编辑时逼他先编一个号码才能改备注，结果只会是一串假号码进库，
 * 而手机号是查重主键——假号码比空着更糟。反过来，原来有号码的不许清空：
 * 那是认人的依据，清掉了下次导入同一个人就认不出来。
 *
 * 空着的电话**不参与查重**（调用方照这个返回的空串跳过）：两个都没留电话的人不是同一个人。
 */
export function 查电话(v: string | null | undefined, opts: { 必填: boolean }): { ok: true; phone: string } | { ok: false; error: string } {
  const 原 = (v ?? "").trim();
  if (!原) return opts.必填 ? { ok: false, error: "请输入联系电话" } : { ok: true, phone: "" };
  // 带 * 的是打了码给人看的样子（共享试用区），不是号码。规整会把 * 去掉、剩下的 7 位数字照样「像号码」，所以在规整之前拦
  if (原.includes("*")) return { ok: false, error: "电话里不能有 *" };
  const phone = 规整手机号(原);
  if (!像手机号(phone)) return { ok: false, error: "电话看不出是个号码（6–20 位数字，可以带 +）" };
  return { ok: true, phone };
}

/**
 * 表单交回来的号码，如果正是我们打码给人看的那个样子（共享试用区，`138****1111`），就当没改、认回原号。
 *
 * 共享区的页面把号码打码后交给表单，人只改了年级，表单把 `138****1111` 原样交回来；
 * 原来服务端看它和库里不一样，规整一下就写进去了——真号被换成带星号的那串，永远找不回来（2026-10-01 排查 A2）。
 * 不是原号打码的样子就原样返回，交给 查电话 去拒。
 */
export function 认回打码号<T extends string | null | undefined>(交回: T, 原: string | null | undefined): T | string {
  const v = (交回 ?? "").trim();
  if (!v.includes("*") || !原) return 交回;
  return maskPhone(原) === v ? 原 : 交回;
}

