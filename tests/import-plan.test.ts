/**
 * 导入管线的纯函数那一半：解析、猜列、逐格校验、合并重复行。
 *
 * 这一组钉的是**导入最容易安静出错的四件事**：
 *
 *   1. 分隔符认错 → 整张表变成一列，而人只知道「文件坏了」
 *   2. 自动猜列猜错 → 电话进了备注栏，没有任何报错
 *   3. 日期猜错 → 人照着一个错的预计签约日期安排下周的工作
 *   4. 手机号没规整 → 同一个人被当成十个人，查重整个失效且毫无迹象
 *
 * 第 4 条是最要命的：导入第二次同一份表就是一整份重复数据。
 */
import { describe, it, expect } from "vitest";
import { 解析CSV, 成表, 认分隔符, 行数上限, 列数上限 } from "@/lib/import/parse";
import { 字段表, 猜列, 规整表头, 像表头 } from "@/lib/import/fields";
import { 摊开, 并重复行, 规整手机号, 像手机号, 认日期, 认枚举, 改动键 } from "@/lib/import/plan";
import { DEFAULT_BUSINESS } from "@/lib/business-config";
import { FOLLOW_STATUSES } from "@/lib/constants";

const b = DEFAULT_BUSINESS;
const 表 = 字段表(b);

describe("CSV 解析", () => {
  it("引号里的逗号和换行不算分隔", () => {
    const r = 解析CSV('姓名,备注\n"张三","他说：先看看,再说\n下周回电"');
    expect(r).toHaveLength(2);
    expect(r[1][0]).toBe("张三");
    expect(r[1][1]).toBe("他说：先看看,再说\n下周回电");
  });

  it("两个双引号是一个双引号", () => {
    expect(解析CSV('a\n"他说""好"""')[1][0]).toBe('他说"好"');
  });

  it("中文 Windows 的 Excel 存出来是分号分隔的，要认出来", () => {
    // 认错的表现是整张表只有一列，而人只知道「文件坏了」
    expect(认分隔符("姓名;手机号;备注")).toBe(";");
    const r = 解析CSV("姓名;手机号\n张三;13800000001");
    expect(r[1]).toEqual(["张三", "13800000001"]);
  });

  it("制表符分隔的（从网页里直接粘出来的那种）也认", () => {
    expect(解析CSV("姓名\t手机号\n张三\t13800000001")[1]).toEqual(["张三", "13800000001"]);
  });

  it("导出的那个 BOM 不能变成表头的一部分", () => {
    // 不吃掉的话第一列表头是「﻿姓名」，猜列直接猜不到
    const { 表头 } = 成表(解析CSV("﻿姓名,手机号\n张三,13800000001"));
    expect(表头[0]).toBe("姓名");
  });

  it("每行列数补齐到表头那么长——Excel 存出来的行长短不一是常态", () => {
    const { 数据 } = 成表(解析CSV("姓名,手机号,备注\n张三,13800000001\n李四,13800000002,好说"));
    expect(数据[0]).toHaveLength(3);
    expect(数据[0][2]).toBe("");
  });

  it("全空的行丢掉，不当成一条没有姓名的记录", () => {
    const { 数据 } = 成表(解析CSV("姓名,手机号\n张三,13800000001\n,\n\n"));
    expect(数据).toHaveLength(1);
  });

  it("超过上限要截断并如实说原表有多少行", () => {
    const 行 = ["姓名,手机号", ...Array.from({ length: 行数上限 + 5 }, (_, i) => `张${i},1380000${String(i).padStart(4, "0")}`)];
    const { 数据, 截断了 } = 成表(解析CSV(行.join("\n")));
    expect(数据).toHaveLength(行数上限);
    expect(截断了?.行).toBe(行数上限 + 5);
  });

  it("列太多也截断", () => {
    const 头 = Array.from({ length: 列数上限 + 3 }, (_, i) => `列${i}`).join(",");
    const { 表头, 截断了 } = 成表(解析CSV(`${头}\n${"x,".repeat(列数上限 + 2)}x`));
    expect(表头).toHaveLength(列数上限);
    expect(截断了?.列).toBe(列数上限 + 3);
  });
});

describe("猜这一列是什么", () => {
  it("表头带空格、冒号、全角、括号都不影响", () => {
    expect(规整表头("手机号 ")).toBe("手机号");
    expect(规整表头("联系电话：")).toBe("联系电话");
    // 括号里的整段要连内容一起去掉：只去括号会变成「姓名必填」，同义词表里没这条
    // 括号里的整段要连内容一起去掉：只去括号会变成「姓名必填」，同义词表里没这条
    expect(规整表头("姓名(必填)")).toBe("姓名");
    expect(规整表头("手机号（必填）")).toBe("手机号");
    expect(规整表头("手机号*")).toBe("手机号");
    expect(规整表头("手机号（必填）")).toBe("手机号");
    expect(规整表头("手机号*")).toBe("手机号");
    expect(规整表头("Ｎａｍｅ")).toBe("name");
  });

  it("常见写法都能对上", () => {
    expect(猜列(["姓名", "联系方式", "公司", "备注"], 表)).toEqual(["name", "phone", "school", "remark"]);
    expect(猜列(["客户姓名", "手机", "来源渠道"], 表)).toEqual(["name", "phone", "channelName"]);
  });

  it("猜不到就是 null，不硬往最近的字段上靠", () => {
    // 猜错比猜不到糟：猜不到人一眼看见空下拉，猜错他直接点了下一步
    expect(猜列(["微信号", "身份证"], 表)).toEqual([null, null]);
  });

  it("两列都像同一个字段时只认第一列", () => {
    // 两列都往 name 里填的结果是后一列静悄悄覆盖前一列
    expect(猜列(["姓名", "客户姓名", "手机号"], 表)).toEqual(["name", null, "phone"]);
  });
});

describe("手机号是认人的那一列", () => {
  it("十种写法规整成同一个——不规整的话同一个人会被当成十个人", () => {
    const 期望 = "13800001111";
    const 写法 = [
      "13800001111",
      "138 0000 1111",
      "138-0000-1111",
      "+8613800001111",
      "8613800001111",
      "'13800001111",          // Excel 把长数字存成文本时加的那个单引号
      "(138)0000-1111",
      "１３８００００１１１１", // 从网页上粘出来的全角
      " 13800001111 ",
    ];
    for (const s of 写法) {
      expect(规整手机号(s), s).toBe(期望);
    }
  });

  it("比表单那条大陆手机号的正则松：座机和海外号也是人真实的客户", () => {
    expect(像手机号("01062345678")).toBe(true);
    expect(像手机号("+1 415 555 2671")).toBe(true);
    expect(像手机号("张三")).toBe(false);
    expect(像手机号("12")).toBe(false);
  });
});

describe("日期：认不出来就留空，绝不猜", () => {
  const 看 = (s: string) => {
    const d = 认日期(s);
    return d ? `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}` : null;
  };
  it("三种面孔都认", () => {
    expect(看("2026-09-19")).toBe("2026-09-19");
    expect(看("2026/9/19")).toBe("2026-09-19");
    expect(看("2026年9月19日")).toBe("2026-09-19");
    expect(看("2026.09.19")).toBe("2026-09-19");
  });
  it("Excel 的日期序列号也认，而且和文本那条路落在同一个时刻", () => {
    // 46284 是 Excel 里的 2026-09-19。序列号算出来的是 UTC 时刻，
    // 文本那条路落的是本地零点——不统一的话，同一天经由 xlsx 和经由 csv 进来
    // 在 UTC 以西的时区里直接差一天，而两边都不报错
    expect(看("46284")).toBe("2026-09-19");
    expect(认日期("46284")!.getTime()).toBe(认日期("2026-09-19")!.getTime());
    expect(认日期("46284")!.getHours()).toBe(0);
  });
  it("不存在的日期不许被滚到下个月", () => {
    // new Date(2026,1,31) 会变成 3 月 3 日，静悄悄的
    expect(认日期("2026-02-31")).toBeNull();
  });
  it("读不懂就是 null", () => {
    expect(认日期("下周")).toBeNull();
    expect(认日期("九月")).toBeNull();
    expect(认日期("12")).toBeNull();
  });
});

describe("枚举：对不上用默认值，不做近似匹配", () => {
  it("完全相等、去空白相等都算", () => {
    expect(认枚举("跟进中", FOLLOW_STATUSES)).toBe("跟进中");
    expect(认枚举(" 跟进中 ", FOLLOW_STATUSES)).toBe("跟进中");
  });
  it("「已联系」不该被猜成「已加微信」——意思差得远，而它是拿来排工作的", () => {
    expect(认枚举("已联系", ["待跟进", "跟进中", "已加微信"])).toBeNull();
  });
});

describe("摊开一张表", () => {
  const 排 = (csv: string, 改过?: Record<string, string>) => {
    const { 表头, 数据 } = 成表(解析CSV(csv));
    return 摊开({ 表头, 数据, 映射: 猜列(表头, 表), 字段表: 表, 改过 });
  };

  it("一格日期读不懂，不该让这个人整条进不来", () => {
    const r = 排("姓名,手机号,预计签约\n张三,13800000001,下周");
    expect(r[0].进不了).toBeUndefined();
    expect(r[0].值.name).toBe("张三");
    expect(r[0].值.expectedSignAt).toBeUndefined();
    expect(r[0].问题[0].严重).toBe("留空");
  });

  it("没有手机号的行进不了，并且说的是手机号不是姓名", () => {
    const r = 排("姓名,手机号\n张三,\n,13800000002");
    expect(r[0].进不了).toContain("手机号");
    expect(r[1].进不了).toContain("姓名");
  });

  it("手机号那一格看不出是号码时，说法要和「压根没填」分开", () => {
    const r = 排("姓名,手机号\n张三,不详");
    expect(r[0].进不了).toContain("看不出");
  });

  it("行号从 2 起——人要照着它回 Excel 里找那一行", () => {
    expect(排("姓名,手机号\n张三,13800000001")[0].行号).toBe(2);
  });

  it("复核那一步改过的值要顶替原值", () => {
    const { 表头, 数据 } = 成表(解析CSV("姓名,手机号,跟进状态\n张三,13800000001,已联系"));
    const 映射 = 猜列(表头, 表);
    const 原 = 摊开({ 表头, 数据, 映射, 字段表: 表 });
    expect(原[0].值.followStatus).toBeUndefined();
    const 改 = 摊开({ 表头, 数据, 映射, 字段表: 表, 改过: { [改动键(2, "已联系")]: "跟进中" } });
    expect(改[0].值.followStatus).toBe("跟进中");
    expect(改[0].问题).toHaveLength(0);
  });
});

describe("压根没有表头的那种表", () => {
  /*
    最安静的一种对不上：第一行就是第一个人。照 成表 的规矩那一行会被当成表头吃掉，
    第一个客户就这么没了，而且一个字的报错都没有。
  */
  it("第一行里有电话号码，就不是表头", () => {
    expect(像表头(["张三", "13800000001", "星辰科技"])).toBe(false);
    expect(像表头(["张三", "138 0000 0001"])).toBe(false);
    expect(像表头(["张三", "+8613800000001"])).toBe(false);
  });

  it("正常表头都判成表头——包括一个字段都对不上的英文表头", () => {
    expect(像表头(["姓名", "手机号", "公司"])).toBe(true);
    // 从别的 CRM 导出来的表一个字段都猜不到，但它确确实实是表头，
    // 所以不能拿「对上了几个字段」当判据
    expect(像表头(["Full Name", "Mobile", "Account", "Lifecycle Stage"])).toBe(true);
  });

  it("表头里带数字不算——「2026年预算」是个正经表头", () => {
    expect(像表头(["姓名", "手机号", "2026年预算"])).toBe(true);
  });
});

describe("表里有我们没有的列", () => {
  /*
    这是导入里最常见的一种落差：人手上那份表有「微信号」「身份证」「客户等级」
    这些我们没有的列。自定义字段是明确不做的，于是只有两条路——
    丢掉，或者并进备注。默认并进，因为丢掉是**看不见的**损失：
    人以为整份表都进来了，几周后才发现微信号一个都没有，而那时原表可能已经改过了。
  */
  const 排 = (csv: string, 没对上的列?: "并进备注" | "丢掉") => {
    const { 表头, 数据 } = 成表(解析CSV(csv));
    return 摊开({ 表头, 数据, 映射: 猜列(表头, 表), 字段表: 表, 没对上的列 });
  };

  it("默认并进备注，写成「表头：值」一行一条", () => {
    const r = 排("姓名,手机号,微信号,客户等级\n张三,13800000001,zhangsan_wx,A");
    expect(r[0].值.remark).toBe("微信号：zhangsan_wx\n客户等级：A");
  });

  it("本来就有备注时接在后面，不覆盖", () => {
    const r = 排("姓名,手机号,备注,微信号\n张三,13800000001,回电积极,zs_wx");
    expect(r[0].值.remark).toBe("回电积极\n微信号：zs_wx");
  });

  it("选了「丢掉」就真的不进备注", () => {
    const r = 排("姓名,手机号,微信号\n张三,13800000001,zs_wx", "丢掉");
    expect(r[0].值.remark).toBeUndefined();
  });

  it("空格子不并进去——「微信号：」这样一条没有任何用处", () => {
    const r = 排("姓名,手机号,微信号,客户等级\n张三,13800000001,,A");
    expect(r[0].值.remark).toBe("客户等级：A");
  });

  it("没有表头的那一列不并进去：一串没有出处的值比丢掉还糟", () => {
    const r = 排("姓名,手机号,\n张三,13800000001,某个值");
    expect(r[0].值.remark).toBeUndefined();
  });

  it("人手工把某一列设成「不导」时，它也算没对上，照样并进备注", () => {
    // 这是刻意的：「不导这一列」在界面上的意思是「它不属于任何字段」，
    // 而不是「把它扔了」——真要扔，关掉那个开关
    const { 表头, 数据 } = 成表(解析CSV("姓名,手机号,公司\n张三,13800000001,星辰科技"));
    const m = 猜列(表头, 表);
    m[2] = null;
    const r = 摊开({ 表头, 数据, 映射: m, 字段表: 表 });
    expect(r[0].值.school).toBeUndefined();
    expect(r[0].值.remark).toBe("公司：星辰科技");
  });
});

describe("同一份表里手机号重复的行", () => {
  const 排 = (csv: string) => {
    const { 表头, 数据 } = 成表(解析CSV(csv));
    return 并重复行(摊开({ 表头, 数据, 映射: 猜列(表头, 表), 字段表: 表 }));
  };

  it("后面的补前面的空，合成一条", () => {
    const { 行, 合掉几行 } = 排("姓名,手机号,备注,公司\n张三,13800000001,,星辰\n张三,138 0000 0001,回电很积极,");
    expect(行).toHaveLength(1);
    expect(合掉几行).toBe(1);
    expect(行[0].值.remark).toBe("回电很积极");
    expect(行[0].值.school).toBe("星辰");
  });

  it("先来的赢：表尾一条残缺的补录行不该抹掉前面完整的那条", () => {
    const { 行 } = 排("姓名,手机号,公司\n张三,13800000001,星辰科技\n张三,13800000001,x");
    expect(行[0].值.school).toBe("星辰科技");
  });

  it("进不了的行各自留着，不参与合并", () => {
    const { 行 } = 排("姓名,手机号\n张三,\n李四,\n王五,13800000003");
    expect(行).toHaveLength(3);
  });
});

/**
 * 开放的枚举：职位 / 年级。
 *
 * 这一档错了不会报错，只会有两种安静的结局：
 *   丢值 —— 人那份表里的「结构工程师」没进来，档案缺一块，他事后才发现
 *   塞脏 —— 反过来，要是把封闭的那两个也放开，有人填了「再看看」，
 *           从此盯盘清单、建议卡、报表分组全都不认识他
 * 所以两边都要钉：grade 收得下，followStatus 收不下。
 */
describe("开放的枚举：对不上就原样收下", () => {
  const 表头 = ["姓名", "手机号", DEFAULT_BUSINESS.fields.grade, "跟进状态"];
  const 跑 = (职位: string, 跟进: string) =>
    摊开({
      表头,
      数据: [["张三", "13800000000", 职位, 跟进]],
      映射: 猜列(表头, 表),
      字段表: 表,
    })[0];

  it("职位不在选项里，值原样进去，并且标成「照收」而不是问题", () => {
    const r = 跑("结构工程师", FOLLOW_STATUSES[0]);
    expect(r.值.grade, "对不上就丢的话，人那份表里的职位就没了").toBe("结构工程师");
    const q = r.问题.find((x) => x.字段 === "grade");
    expect(q?.严重).toBe("照收");
  });

  it("在选项里的照旧规整成标准写法", () => {
    const r = 跑(DEFAULT_BUSINESS.grades[0], FOLLOW_STATUSES[0]);
    expect(r.值.grade).toBe(DEFAULT_BUSINESS.grades[0]);
    expect(r.问题.find((x) => x.字段 === "grade")).toBeUndefined();
  });

  it("**跟进状态不能开**：它被盯盘、建议卡、报表分组吃着，认不出就得用默认值", () => {
    const r = 跑("结构工程师", "再看看");
    const q = r.问题.find((x) => x.字段 === "followStatus");
    expect(q?.严重, "放开这一个的后果是统计悄悄漏人").toBe("用默认");
    expect(r.值.followStatus, "没认出来就不该写进去").toBeUndefined();
  });

  it("字段表里只有职位是开放的——别的字段被顺手放开了要在这儿红", () => {
    const 开着的 = 表.filter((f) => f.开放).map((f) => f.名);
    expect(开着的).toEqual(["grade"]);
  });
});
