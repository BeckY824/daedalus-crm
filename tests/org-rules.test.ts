/**
 * 企业版组织规则的规整和合并（lib/project/org-rules.ts）：默认全关；存坏的退回默认；
 * 界面填错的报出来不偷偷改；每人上限整份替换、null 删掉单独设置。
 */
import { describe, it, expect } from "vitest";
import { 规整组织规则, 合上改动, 持有上限of, 默认组织规则, 负责人可推 } from "@/lib/project/org-rules";

describe("规整组织规则", () => {
  it("没存过、存坏了：全是默认（上限关着）", () => {
    expect(规整组织规则(undefined)).toEqual(默认组织规则);
    expect(规整组织规则("乱")).toEqual(默认组织规则);
    expect(规整组织规则({ 公海: 3 })).toEqual(默认组织规则);
    expect(默认组织规则.公海.持有上限开).toBe(false);
  });

  it("超出范围、不是整数的退回默认或丢掉；不认识的 key 丢掉；数字字符串认", () => {
    expect(规整组织规则({
      别的: 1,
      公海: { 持有上限开: "true", 默认上限: 0, 每人上限: { a: 3, b: -1, c: 1.5, d: "7", e: 1000, "": 2 } },
    })).toEqual({ 公海: { 持有上限开: false, 默认上限: 30, 每人上限: { a: 3, d: 7 } }, 超时回收: { 开: false, 节点天数: {} }, 节点推进: { 开: false, 必填: {} }, 阶段: 默认组织规则.阶段 });
    expect(规整组织规则({ 公海: { 持有上限开: true, 默认上限: "12" } }).公海).toMatchObject({ 持有上限开: true, 默认上限: 12 });
  });
});

describe("合上改动", () => {
  it("只改传了的；开关、默认、每人分开改", () => {
    const 开了 = 合上改动(默认组织规则, { 公海: { 持有上限开: true } });
    expect(开了).toEqual({ 公海: { 持有上限开: true, 默认上限: 30, 每人上限: {} }, 超时回收: { 开: false, 节点天数: {} }, 节点推进: { 开: false, 必填: {} }, 阶段: 默认组织规则.阶段 });
    const 设了 = 合上改动(开了 as never, { 公海: { 默认上限: 10, 每人上限: { a: 0, b: 5 } } });
    expect(设了).toEqual({ 公海: { 持有上限开: true, 默认上限: 10, 每人上限: { a: 0, b: 5 } }, 超时回收: { 开: false, 节点天数: {} }, 节点推进: { 开: false, 必填: {} }, 阶段: 默认组织规则.阶段 });
  });

  it("每人上限整份替换：传 null / 空的人回到默认", () => {
    const 现在 = { ...默认组织规则, 公海: { 持有上限开: true, 默认上限: 10, 每人上限: { a: 1, b: 2 } } };
    expect(合上改动(现在, { 公海: { 每人上限: { a: null, b: 3 } } })).toEqual({ ...默认组织规则, 公海: { 持有上限开: true, 默认上限: 10, 每人上限: { b: 3 } } });
  });

  it("填错的报出来", () => {
    expect(合上改动(默认组织规则, { 公海: { 默认上限: 0 } })).toEqual({ error: "默认持有上限请填 1–999 的整数" });
    expect(合上改动(默认组织规则, { 公海: { 默认上限: 2.5 } })).toMatchObject({ error: expect.stringContaining("整数") });
    expect(合上改动(默认组织规则, { 公海: { 每人上限: { a: -1 } } })).toEqual({ error: "单独设的上限请填 0–999 的整数" });
    expect(合上改动(默认组织规则, { 公海: { 持有上限开: "开" as never } })).toEqual({ error: "持有上限开关只能开或关" });
    expect(合上改动(默认组织规则, null as never)).toEqual({ error: "要改什么？" });
  });
});

describe("持有上限of", () => {
  it("关着 = 不限；开着用单独设的，没设用默认；0 也算单独设了", () => {
    const 规则 = { ...默认组织规则, 公海: { 持有上限开: false, 默认上限: 10, 每人上限: { a: 0 } as Record<string, number> } };
    expect(持有上限of(规则, "a")).toBeNull();
    规则.公海.持有上限开 = true;
    expect(持有上限of(规则, "a")).toBe(0);
    expect(持有上限of(规则, "b")).toBe(10);
  });
});

describe("超时回收设置", () => {
  it("默认关、没设节点；存坏的节点、天数丢掉", () => {
    expect(默认组织规则.超时回收).toEqual({ 开: false, 节点天数: {} });
    expect(规整组织规则({ 超时回收: { 开: true, 节点天数: { 潜客培育: 7, 线索验证: "3", 生产备货: 5, 明确需求: 0, 共识方案: 400, 别的: 2 } } }).超时回收)
      .toEqual({ 开: true, 节点天数: { 潜客培育: 7, 线索验证: 3 } });
    expect(规整组织规则({ 超时回收: { 开: "true", 节点天数: [] } }).超时回收).toEqual({ 开: false, 节点天数: {} });
  });

  it("节点天数整份替换；null / 空 = 这个节点不回收；改超时回收不动持有上限", () => {
    const 现在 = { ...默认组织规则, 公海: { 持有上限开: true, 默认上限: 8, 每人上限: {} }, 超时回收: { 开: true, 节点天数: { 潜客培育: 7, 线索验证: 3 } } };
    const r = 合上改动(现在, { 超时回收: { 节点天数: { 潜客培育: null, 线索验证: "5", 明确需求: "" } } });
    expect(r).toEqual({ ...现在, 超时回收: { 开: true, 节点天数: { 线索验证: 5 } } });
    expect(合上改动(现在, { 超时回收: { 开: false } })).toEqual({ ...现在, 超时回收: { 开: false, 节点天数: { 潜客培育: 7, 线索验证: 3 } } });
  });

  it("填错的报出来：订单阶段节点、不认识的节点、天数超范围", () => {
    expect(合上改动(默认组织规则, { 超时回收: { 节点天数: { 生产备货: 3 } } })).toEqual({ error: "「生产备货」不是线索、商机阶段的节点，不能设处理时长" });
    expect(合上改动(默认组织规则, { 超时回收: { 节点天数: { 乱写: 3 } } })).toMatchObject({ error: expect.stringContaining("「乱写」") });
    expect(合上改动(默认组织规则, { 超时回收: { 节点天数: { 潜客培育: 0 } } })).toEqual({ error: "「潜客培育」的处理时长请填 1–365 的整数（天）" });
    expect(合上改动(默认组织规则, { 超时回收: { 节点天数: { 潜客培育: 1.5 } } })).toMatchObject({ error: expect.stringContaining("1–365") });
    expect(合上改动(默认组织规则, { 超时回收: { 开: 1 as never } })).toEqual({ error: "超时回收开关只能开或关" });
    expect(合上改动(默认组织规则, { 超时回收: { 节点天数: "7" as never } })).toEqual({ error: "节点时长格式不对，刷新再试" });
  });
});

describe("节点推进设置（D-37）", () => {
  it("默认关、没配；存坏的节点、不认识的必填项丢掉，重复的去掉，空清单不算配", () => {
    expect(默认组织规则.节点推进).toEqual({ 开: false, 必填: {} });
    expect(规整组织规则({ 节点推进: { 开: true, 必填: { 潜客培育: ["来源", "来源", "乱写", 3], 线索验证: [], 尾款结算: ["金额"], 别的: ["金额"], 明确需求: "需求" } } }).节点推进)
      .toEqual({ 开: true, 必填: { 潜客培育: ["来源"] } });
    expect(规整组织规则({ 节点推进: { 开: "true", 必填: [] } }).节点推进).toEqual({ 开: false, 必填: {} });
  });

  it("必填整份替换：null / 空 = 这个节点不配；改节点推进不动别的规则", () => {
    const 现在 = { ...默认组织规则, 超时回收: { 开: true, 节点天数: { 潜客培育: 7 } }, 节点推进: { 开: true, 必填: { 潜客培育: ["来源"], 线索验证: ["国家"] } } };
    expect(合上改动(现在, { 节点推进: { 必填: { 潜客培育: null, 线索验证: ["国家", "国家", "客户等级"], 明确需求: [] } } }))
      .toEqual({ ...现在, 节点推进: { 开: true, 必填: { 线索验证: ["国家", "客户等级"] } } });
    expect(合上改动(现在, { 节点推进: { 开: false } })).toEqual({ ...现在, 节点推进: { 开: false, 必填: 现在.节点推进.必填 } });
  });

  it("填错的报出来：最后一个节点、不认识的节点、不认识的必填项、格式不对", () => {
    expect(合上改动(默认组织规则, { 节点推进: { 必填: { 尾款结算: ["金额"] } } })).toEqual({ error: "「尾款结算」不能配必填（最后一个节点由人点成功交付）" });
    expect(合上改动(默认组织规则, { 节点推进: { 必填: { 乱写: ["金额"] } } })).toEqual({ error: "「乱写」不是项目节点，刷新再试" });
    expect(合上改动(默认组织规则, { 节点推进: { 必填: { 潜客培育: ["报价单"] } } })).toEqual({ error: "「报价单」不是能选的必填项，刷新再试" });
    expect(合上改动(默认组织规则, { 节点推进: { 必填: { 潜客培育: "来源" as never } } })).toEqual({ error: "必填清单格式不对，刷新再试" });
    expect(合上改动(默认组织规则, { 节点推进: { 必填: "x" as never } })).toEqual({ error: "必填清单格式不对，刷新再试" });
    expect(合上改动(默认组织规则, { 节点推进: { 开: "1" as never } })).toEqual({ error: "节点推进开关只能开或关" });
  });
});

describe("阶段规则（企业版 10-26：往前推权限 + 出口叫法）", () => {
  it("默认负责人可推、没改叫法；存坏的退回默认、坏了的阶段丢掉", () => {
    expect(默认组织规则.阶段).toEqual({ 推进权限: "负责人可推", 出口叫法: {} });
    expect(规整组织规则({ 阶段: { 推进权限: "谁都能推", 出口叫法: "乱" } }).阶段).toEqual(默认组织规则.阶段);
    expect(规整组织规则({ 阶段: { 推进权限: "仅上级推", 出口叫法: { 线索: ["转了", null], 商机: ["x".repeat(20), "y"], 别的: ["a", "b"] } } }).阶段)
      .toEqual({ 推进权限: "仅上级推", 出口叫法: { 线索: ["转了", null] } });
  });

  it("合上改动：只改传了的；填错的报出来", () => {
    const 改了 = 合上改动(默认组织规则, { 阶段: { 推进权限: "仅上级推" } });
    expect(改了).toMatchObject({ 阶段: { 推进权限: "仅上级推", 出口叫法: {} } });
    expect(负责人可推(改了 as never)).toBe(false);
    expect(负责人可推(默认组织规则)).toBe(true);
    const 叫法 = 合上改动(改了 as never, { 阶段: { 出口叫法: { 商机: [" 签了 ", ""] } } });
    expect(叫法).toMatchObject({ 阶段: { 推进权限: "仅上级推", 出口叫法: { 商机: ["签了", null] } } });
    expect(合上改动(默认组织规则, { 阶段: { 推进权限: "随便" as never } })).toMatchObject({ error: expect.stringContaining("往前推权限") });
    expect(合上改动(默认组织规则, { 阶段: { 出口叫法: { 商机: ["x".repeat(11), null] } } })).toMatchObject({ error: expect.stringContaining("出口叫法") });
    expect(合上改动(默认组织规则, { 阶段: { 出口叫法: { 商机: ["一样", "一样"] } } })).toMatchObject({ error: expect.stringContaining("不能叫一样") });
    expect(合上改动(默认组织规则, { 阶段: { 出口叫法: { 别的: ["a", "b"] } } })).toMatchObject({ error: expect.stringContaining("没有「别的」") });
  });
});
