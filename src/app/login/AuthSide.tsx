import { PixelLogo } from "@/components/Logo";
import TypeBrand from "./TypeBrand";

/**
 * 门口的左栏：像素标 + 打字机名字、一句话、一段说清楚的小字。
 * 登录 / 注册 / 找回密码共用，几扇门长得一样。
 *
 * 2026-10-04 起网页版也用这一套（用户：「网页端的登录页面是不是也没同步桌面端已修改的样子？」）。
 * 样子一样，**话按各自的实情说**：桌面端那句「都在你自己的电脑上」放到网页版就是假话。
 */
export type 门口 = "桌面端" | "托管版" | "自部署";

const 话: Record<门口, { 一句: string; 小字: string }> = {
  桌面端: {
    一句: "客户、跟进、开发信，都在你自己的电脑上。",
    /*
      **把拦得住和拦不住的都说出来**（原来在登录卡片底下，搬到这儿）。
      数据按云端账号分开存（desktop/accounts.js），换个账号登录看到的是他自己那一份；
      但同一个电脑账户下，拿 SQLite 工具直接打开对方的库文件，应用层分目录是拦不住的。
    */
    小字: "数据只存在这台电脑上，账号只用来记 AI 次数。每个账号各存一份；同一个电脑账户下的人仍能翻到彼此的数据文件，要彻底分开请各用各的电脑账户。",
  },
  托管版: {
    一句: "客户、跟进、开发信，一个地方管起来。",
    // 网页版 = 一个共享试用工作区（固定账号发给团队），注册开的是桌面端用的云端账号。见 memory web-trial-shared-workspace
    小字: "网页版是团队共用的试用工作区，数据存在我们的云服务器上，用团队发给你的账号登录。想让数据只留在自己电脑上，下载桌面端，用注册的邮箱登录。",
  },
  自部署: {
    一句: "客户、跟进、开发信，跑在你们自己的服务器上。",
    小字: "账号由管理员在「设置 → 团队成员」里开；忘了密码，请管理员在那儿帮你重置。",
  },
};

export default function AuthSide({ 门 = "桌面端" }: { 门?: 门口 }) {
  return (
    <aside className="auth-side">
      <div className="auth-mark">
        <PixelLogo size={96} />
        <TypeBrand />
      </div>
      <p className="auth-claim">{话[门].一句}</p>
      <p className="auth-fine">{话[门].小字}</p>
    </aside>
  );
}
