/**
 * 导入猜列的**兜底**：规则先跑，规则认不出来的那几列才问判断模型。
 *
 * ## 规则命中的列，这里一个字都不碰
 *
 * `猜列()` 那张同义词表是「几乎不可能是别的意思」的说法，命中即定论。
 * 这一层只处理它留下的 null。这样做的结果是：关掉开关、断网、没配 key，
 * 导入的行为和今天**一模一样**，不是退化，是原样。
 *
 * ## 不另写一份字段字典
 *
 * 给模型看的选项说明是从 `字段表(b)` 现生成的，不是手抄一份。
 * 手抄的那份迟早和 fields.ts 对不上——而对不上的表现是「猜出来的字段界面上没有」，
 * 不报错，只是那一列静悄悄留空。项目里那八份必须一致的清单，教训都在这儿。
 * 顺带：院校 / 年级 / 专业跟着业务配置走，派生出来的说明自动就跟着走了。
 *
 * ## 这些文字是代码，不是提示词
 *
 * 2026-09-20 实测：同一批例子，把「拿不准就弃权」写含糊和逐条摊开，
 * 差了两个量级的置信裕度（0.51–0.83 对 0.80–0.95）。别顺手改措辞——
 * 改了就跑 `npm run test:jev`（真打接口那套，见 tests/jev/）。
 */
/*
  只引类型，不引运行时。
  SDK 的 `choice(a, b)` 造的就是下面这个 `{ type, instructions, criteria }` 字面量，
  自己写一遍比多一条运行时依赖划算——**这个文件客户端组件要引**（导入抽屉拿 `并进来`
  去合并后到的结果），运行时引了 SDK 就等于把它整个打进浏览器包。
*/
import type { ChoiceQuestion } from "@typesafe-ai/sdk";
import type { 字段名, 字段规格 } from "../import/fields";
import type { 选择答案 } from "./client";

/** 「以上都不是」。Choice 的概率和恒为 1，没有这一项就一定会硬塞给某个字段 */
export const 弃权 = "_skip";

/**
 * 低于这个置信度就当没猜。
 *
 * 0.6 是实测挑的：对抗题里唯一一条该拦的（渠道列恰好全是人名）落在 0.32，
 * 而该过的最低一条是 0.55。留出这段距离，宁可多让人点两下。
 */
export const 置信阈值 = 0.6;

/** 给模型看几行样例。三行够分辨「状态」是跟进状态还是意向度，再多只是多花钱 */
export const 样例行数 = 3;

const 问题名 = (i: number) => `c${i}`;

/** 从字段表现生成选项说明。枚举字段连合法值一起给——「状态」那种列只能靠值分辨 */
function 选项(表: 字段规格[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const f of 表) {
    // 去重：别名表里第一条常常就是 label 本身（院校 / 年级 / 专业跟着业务配置走时更明显），
    // 原样拼出来是「院校（表头常写成：院校、院校、学校…）」——喂给模型的字，不该是这样
    const 别名 = [...new Set(f.别名)].slice(0, 8).join("、");
    const 取值 = f.values?.length ? `，值通常是 ${f.values.slice(0, 6).join("、")} 这一类` : "";
    out[f.名] = `${f.label}（表头常写成：${别名}${取值}）`;
  }
  out[弃权] =
    "以上都不是。三种情况都选这一项：我们没有这个字段；" +
    "表头看不出是什么、值也看不出是什么（比如值是 A、B 这种没有含义的代号，或者整列都空）；" +
    "以及表头像某个字段但值对不上。留空让人自己挑，永远好过填错一个字段。";
  return out;
}

/**
 * 只给规则弃权的那几列组问题。全都认出来了就返回空对象，调用方据此不发请求。
 *
 * @param 数据 原始行。只取前 {@link 样例行数} 行的对应格子
 */
export function 组问题(
  表头: readonly string[],
  数据: readonly (readonly string[])[],
  规则: readonly (字段名 | null)[],
  表: 字段规格[],
): Record<string, ChoiceQuestion> {
  const 说明 = 选项(表);
  const out: Record<string, ChoiceQuestion> = {};
  表头.forEach((h, i) => {
    if (规则[i] !== null) return;
    const 样例 = 数据
      .slice(0, 样例行数)
      .map((r) => (r[i] ?? "").trim())
      .map((v) => (v === "" ? "（空）" : v));
    out[问题名(i)] = {
      type: "choice",
      instructions:
        `这一列对应哪个字段？表头「${h}」，前 ${样例.length} 行：${样例.join("、")}。` +
        `拿不准、或者我们没有这个字段，就选 ${弃权}——宁可不导入，也不要填错字段。`,
      criteria: 说明,
    };
  });
  return out;
}

/**
 * 把模型的答案并进规则的结果。**规则赢，人赢，模型垫底。**
 *
 * 三道闸，少一道都会出静悄悄的错：
 *   1. 选了弃权、或者置信不够 → 仍然留空，让人自己选
 *   2. 不在字段表里的答案一律丢掉——模型回一个我们没有的名字，界面上就是个空下拉
 *   3. **去重**：同一个字段只认第一列。Jev 把每一列当独立问题并行回答，彼此看不见，
 *      所以「联系方式」和「TEL」它会都判成 phone；两列都往 phone 里填的结果是
 *      后一列覆盖前一列，一声不吭。这条和 `猜列()` 里那个 `用掉` 集合是同一条规矩。
 */
export function 并进来(
  规则: readonly (字段名 | null)[],
  答案: Record<string, 选择答案> | null,
  表: 字段规格[],
): (字段名 | null)[] {
  const 出 = [...规则];
  if (!答案) return 出;
  const 合法 = new Set<string>(表.map((f) => f.名));
  const 用掉 = new Set<字段名>(出.filter((x): x is 字段名 => x !== null));
  出.forEach((已有, i) => {
    if (已有 !== null) return;
    const a = 答案[问题名(i)];
    if (!a || a.选 === 弃权 || a.置信 < 置信阈值) return;
    if (!合法.has(a.选)) return;
    const f = a.选 as 字段名;
    if (用掉.has(f)) return;
    用掉.add(f);
    出[i] = f;
  });
  return 出;
}
