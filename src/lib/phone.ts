/**
 * 客户电话的规矩：怎么规整、怎样算「像个号码」、什么时候必填。
 *
 * **导入、客户表单、服务端 saveCustomer 三处共用这一份。** 2026-09-28 审查 S2：
 * 导入故意放宽（收海外号、座机），表单却用大陆 11 位手机号的正则，
 * 结果导进来的人以后一编辑就被卡住，外贸用户的海外客户根本建不了。
 * 两处各写一条规矩，迟早有一条落后——所以只留这一处。
 *
 * 纯函数，浏览器和服务端都能用。
 */
import { maskPhone } from "./utils";

/**
 * 手机号规整：只留数字，去掉国家码和分隔符。
 *
 * 为什么非规整不可：这是认人的那一列。Excel 里同一个号码有十种写法
 * （`138 0000 1111`、`138-0000-1111`、`+86 13800001111`、被存成文本的 `'13800001111'`），
 * 不规整的话同一个人会被当成十个人，而查重是**精确比对**——
 * 一个空格就足以让「跳过重复」这件事整个失效，且毫无迹象。
 * 表单那条路也走这里：人手敲的「138 0000 1111」和导入进来的「13800001111」得是同一个人。
 */
export function 规整手机号(v: string): string {
  let s = v.replace(/[０-９]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0)).replace(/＋/g, "+").trim();
  s = s.replace(/^'/, "");
  // 有的系统导出 CSV 时把号码当数字写成「13800001111.0」：先把这个尾巴去掉，不然点被删后成了 12 位的另一个号（2026-10-02 排查）
  s = s.replace(/^(\+?\d[\d\s\-]*)\.0+$/, "$1");
  /*
    英文分机写法（「+1 415 555 0132 ext 12」「x12」「ext. 801」）先统一成「转」：
    不然下面「号码中间夹字母就不猜」把它当成打错的号整格拒掉（第三轮 B3）。光一个 x 要前面有空格，「1380000x1111」照旧算打错
  */
  s = 统一分机(s);
  /*
    一格里写了两个手机号（「13800001111 13900002222」「13800001111/13900002222」）：取第一个。
    要在去掉空格之前认——去掉以后两个号连成 22 位，整行被当成「不像号码」挡下（第二轮 r2-data）。
    导入那条路会把原文并进备注（号码带着字），第二个号不会丢
  */
  const 去横杠 = s.replace(/[\-()（）－—–‐‑‒―]/g, "");
  const 多个手机 = 去横杠.match(/(?<!\d)1[3-9]\d{9}(?!\d)/g);
  if (多个手机 && 多个手机.length > 1) return 多个手机[0];
  // 分隔符：半角 / 全角横杠、各种破折号、空格、括号、点（全角横杠原来漏了，「138－0000－1111」原样进库、认不出是同一个人，第二轮 R2-1）
  s = s.replace(/[\s\-()（）.－—–‐‑‒―]/g, "");
  /*
    号码前后带着字（「13800001111（微信同号）」「手机:13800001111」「QQ 12345678 / 13800001111」）：只取那一串号码。
    有大陆手机号就取它（原来取的是第一串数字，QQ 号被当成了手机号，第二轮复查）；
    座机带分机（「01012345678转801」）留着分机；号码中间夹着字母的（「138O0001111」打错）不猜，交给 像手机号 去拒。
    带 * 的是打码给人看的样子，同样不猜。
  */
  if (!s.includes("*") && /[^\d+]/.test(s) && !/\d[A-Za-z]+\d/.test(s)) {
    // 左边不能紧挨数字或 +：「+1 415 555 0132 (cell)」的 14155550132 正好长得像大陆手机号，原来 + 被丢了（第三轮 B2）
    const 手机 = s.match(/(?<![\d+])(?:\+?0*86)?(1[3-9]\d{9})(?!\d)/);
    const 分机 = s.match(/(\+?\d{6,20})(?:转|分机|ext\.?|EXT\.?|#)(\d{1,6})/);
    const 第一串 = s.match(/\+?\d{6,20}/);
    if (手机) s = 手机[1];
    else if (分机) s = `${分机[1]}转${分机[2]}`;
    else if (第一串) s = 第一串[0];
  }
  s = s.replace(/^\+?0*86(?=\d{11}$)/, "");
  return s;
}

/**
 * 带分机的号码（「01012345678转801」）去掉分机后的主号；不带分机原样返回。
 *
 * 0.46.15 之前分机是被丢掉的，老库里同一个人存的是「01012345678」。现在规整出来带着分机，
 * 查重要是只拿整串精确比，同一张表再导一次就重复建人（第三轮 B4）。所以查重时主号也认：见 同号写法。
 */
export function 主号(p: string): string {
  return p.replace(/转\d+$/, "");
}

/** 查重时这几种写法都算同一个号：本身，和（带分机时）只存了主号的老写法。拿去 `phone: { in: … }` */
export function 同号写法(p: string): string[] {
  const m = 主号(p);
  return m === p ? [p] : [p, m];
}

/**
 * 英文分机写法（「ext 12」「ext. 801」「 x12」）统一成「转」。分机后面还带一点字（「x12 (office)」）也认（第四轮 C4）。
 * 光一个 x 要前面有空格，「1380000x1111」照旧算打错
 */
function 统一分机(s: string): string {
  return s.replace(/(?:\s*ext\.?\s*|\s+x\s*)(\d{1,6})(?=\D*$)/i, "转$1");
}

/** 规整时有没有丢掉号码以外的字（「微信同号」这种）：导入据此把原文并进备注，一个字都不丢 */
export function 号码带着字(v: string): boolean {
  const 去 = 统一分机(v.replace(/[０-９]/g, "0").replace(/^'/, "").replace(/\.0+$/, "")).replace(/[\s\-()（）.－—–‐‑‒―]/g, "");
  if (去.includes("*") || /\d[A-Za-z]+\d/.test(去)) return false;
  const 规 = 规整手机号(v);
  // 原文写了分机、规整出来没有（大陆手机号后面写「ext 8」）：分机算丢了的字，原文进备注（第四轮 C4）
  if (/转\d/.test(去) && !规.includes("转")) return true;
  // 留着分机，但分机后面还有别的字（「x12 (office)」）：那些字丢了
  if (规.includes("转") && /[^\d+]/.test(去.replace(/转|分机|ext\.?|#/gi, ""))) return true;
  // 去掉分隔符后还有号码以外的字，而规整出来是一串纯号码：那些字被丢了。「转 801」这种留着分机的不算
  if (/[^\d+]/.test(去) && /^\+?\d+$/.test(规)) return true;
  // 两个号连写被取了第一个：第二个也算「丢了的字」
  return /^\d+$/.test(去) && 去.length > 规.length + 3 && !去.endsWith(规);
}

/**
 * 看着像个号码吗。
 *
 * **故意不用大陆手机号的正则 `/^1[3-9]\d{9}$/`。** 人手上真有座机、真有带分机号的、
 * 真有海外号码。用大陆手机号去卡，等于告诉人「你这三十个客户不合法」——
 * 而他们明明是他的客户。
 *
 * 只挡两种：根本没有数字（把姓名列当成手机号列对错了），和长得离谱。
 */
export function 像手机号(s: string): boolean {
  // 打了码的（138****1111）不是号码：规整后还剩 7 位数字、长度上过得去，导入会把它当查重主键收下（2026-10-02 排查 X9）
  if (s.includes("*")) return false;
  // 号码中间夹着字母（「138O0001111」把 0 打成了 O）：不是号码，原来会被截成 7 位的另一个号存下（第二轮复查）
  if (/\d[A-Za-z]+\d/.test(s)) return false;
  const 数字 = s.replace(/\D/g, "");
  return 数字.length >= 6 && 数字.length <= 20;
}

/**
 * 表单和 saveCustomer 用的那一句：这个电话能不能存、存成什么。
 *
 * **必填只管新建，和「原来就有号码的」。** 演示数据、线索转过来的、AI 建的档案里
 * 真有没电话的人；编辑时逼他先编一个号码才能改备注，结果只会是一串假号码进库，
 * 而手机号是查重主键——假号码比空着更糟。反过来，原来有号码的不许清空：
 * 那是认人的依据，清掉了下次导入同一个人就认不出来。
 *
 * 空着的电话**不参与查重**（调用方照这个返回的空串跳过）：两个都没留电话的人不是同一个人。
 */
export function 查电话(v: string | null | undefined, opts: { 必填: boolean }): { ok: true; phone: string } | { ok: false; error: string } {
  const 原 = (v ?? "").trim();
  if (!原) return opts.必填 ? { ok: false, error: "请输入联系电话" } : { ok: true, phone: "" };
  // 带 * 的是打了码给人看的样子（共享试用区），不是号码。规整会把 * 去掉、剩下的 7 位数字照样「像号码」，所以在规整之前拦
  if (原.includes("*")) return { ok: false, error: "电话里不能有 *" };
  const phone = 规整手机号(原);
  if (!像手机号(phone)) return { ok: false, error: "电话看不出是个号码（6–20 位数字，可以带 +）" };
  return { ok: true, phone };
}

/**
 * 表单交回来的号码，如果正是我们打码给人看的那个样子（共享试用区，`138****1111`），就当没改、认回原号。
 *
 * 共享区的页面把号码打码后交给表单，人只改了年级，表单把 `138****1111` 原样交回来；
 * 原来服务端看它和库里不一样，规整一下就写进去了——真号被换成带星号的那串，永远找不回来（2026-10-01 排查 A2）。
 * 不是原号打码的样子就原样返回，交给 查电话 去拒。
 */
export function 认回打码号<T extends string | null | undefined>(交回: T, 原: string | null | undefined): T | string {
  const v = (交回 ?? "").trim();
  if (!v.includes("*") || !原) return 交回;
  return maskPhone(原) === v ? 原 : 交回;
}

