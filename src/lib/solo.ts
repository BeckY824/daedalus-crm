/**
 * 列表页上「负责人」这一整层维度要不要摆（审查 D2 / M3）。
 *
 * 表单那边早有 `独自一人`（lib/utils.ts）：只有一个人时不问归属。可列表页一直照摆——
 * 负责人列、「全部负责人 / 全部成员」筛选、计划页的「我的 / 全部成员」、数据页的按人拆分，
 * 在桌面端（一人公司）里每一格都是同一个名字。13 寸窗口下这一列还正好把「最近跟进」「时间」
 * 挤出视野（M3）。少即是多：只有一个人的库里，这一层整个不出现。
 *
 * 判据两条都要满足：
 *   1. 候选名单里至多一个人（和 唯一负责人() / 独自一人 同一个口径）
 *   2. 眼前每一行的负责人都是他（或者没填）——库里还挂着停用同事名下的旧记录时，
 *      这一列就是有信息的，藏起来等于悄悄抹掉归属
 */
export function 列表不问归属(候选: { name: string }[], 行负责人: (string | null | undefined)[]): boolean {
  if (候选.length > 1) return false;
  const 我 = 候选[0]?.name;
  return 行负责人.every((n) => !n || n === "—" || n === 我);
}

/** 有稳定ID的列表按身份判断；同名的停用成员不是当前唯一成员。 */
export function 列表不问归属ID(候选: { id: string }[], 行负责人: (string | null | undefined)[]): boolean {
  return 候选.length <= 1 && 行负责人.every(id => !id || id === 候选[0]?.id);
}
