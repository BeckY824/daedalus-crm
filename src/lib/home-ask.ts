/**
 * ⌘K「问一句」→ 首页发问的交接（2026-10-04，回归核对 J-158）。
 *
 * 原来首页一看到地址上有 ?q= 就直接发出去：别人发来的 /dashboard?q=… 链接点一下就白扣一次 AI 次数
 * （开户只送 30 次、不再补）。现在只认**本应用里 ⌘K 刚交过来的那一句**：
 * ⌘K 走的是客户端跳转，和首页在同一个 JS 运行环境里，模块里这个变量还在；
 * 从外面点进来的链接是整页加载，这个变量是空的——那就只把问题填进输入框，等人自己按回车。
 */
let 刚交过来的: string | null = null;

/** ⌘K 跳去首页之前调一下 */
export function 交给首页问(问题: string) {
  刚交过来的 = 问题.trim();
}

/** 首页看到地址上的 q 时问一下：是不是本应用自己刚交过来的。问过就清掉，一句只认一次 */
export function 是刚交过来的(问题: string): boolean {
  const 是 = 刚交过来的 !== null && 刚交过来的 === 问题.trim();
  刚交过来的 = null;
  return 是;
}
