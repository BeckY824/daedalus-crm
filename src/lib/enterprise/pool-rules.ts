import { 企业版 } from "./switch";

export const 公海规则 = {
  /**
   * 原负责人能不能把自己放进公海（或被收回）的客户、项目再领回去。10-26 定稿「非原负责人均可领取」：
   * 不能。领取接口回「原负责人不能领回」，界面上领取按钮灰着（10-24 那条「谁都能领，包括原负责人」作废）
   */
  原负责人能领回: false,
  /** 客户名下只有这一个项目，项目进了项目公海（主动放回、超时回收），客户也一起进客户公海（确认单第 5 条） */
  单项目客户跟着进公海: true,
  /** 领上面那种项目时，客户也一起领过来（客户和项目不拆开） */
  领项目带走单项目客户: true,
  /** 领 / 分配客户公海里的客户，这位客户名下放在项目公海里的项目也一起归领的人（「领客户即领项目」） */
  领客户带走公海里的项目: true,
};

export const 单项目客户进公海理由 = "名下唯一的项目进了项目公海，客户一起放进公海";

/** 领取接口拒原负责人时回的话（两级公海同一句） */
export const 原负责人不能领回提示 = "原负责人不能领回";

/** 企业版、且规则不让原负责人领回：两级公海都拦。不是企业版回 false，照原来的规矩（客户能自己领回、项目不能），由调用方处理 */
export function 拦原负责人(): boolean {
  return 企业版() && !公海规则.原负责人能领回;
}
