/**
 * 意图直连：**把确定的事从模型手里拿走**。
 *
 * 「这个月谁签得最多」「有哪些渠道」「今天该跟谁」——这类问题的答案是一条**确定的查询**。
 * 让模型每次重新决定一遍，既慢（多一次决策往返，十几秒）又留着抖动的余地
 * （同一个问题今天选对、明天可能选错）。而业务逻辑和字段是固定的，本来就不该每次重新推理。
 *
 * 所以命中这张表的问题直接执行工具，模型只负责最后把数据说成人话——那一步它很稳。
 * 没命中的照常走 agent 循环（那条路要处理的是真正开放的问题）。
 *
 * **宁可漏，不可错。** 每条规则都要求足够具体：模糊的问句（「最近怎么样」）一律不匹配，
 * 让它去走循环。漏了只是慢一点，错了是答非所问。
 *
 * 加规则的依据不是拍脑袋：没命中的问题会记在日志里（run.ts 的 `[intent] 没命中`），
 * 照着真实问句加。
 */

export type 意图 = {
  /** 规则名，出现在日志和用例里 */
  名: string;
  /** 命中就直接跑这一串工具（按顺序） */
  工具: { name: string; args: Record<string, unknown> | ((m: RegExpMatchArray | null, q: string) => Record<string, unknown>) }[];
  /** 匹配。第一条命中即止，所以顺序有意义：具体的放前面 */
  配: RegExp;
  /** 这条规则挡的是什么问句，写给下一个改它的人看 */
  例: string;
};

/**
 * 把「谁提到过 X」里的 X 摘干净。
 *
 * 正则的动词段就算按「从长到短」枚举也挡不住回溯：「谁提到过」会退成
 * 动词「提到」+ 关键词「过」，于是搜了个「过」字，满库都是。
 * 所以剩一道显式的闸：剩下的全是语气词 / 动词尾巴就当没摘到，
 * 让这句话落回 agent 循环（那边会问清楚要搜什么）。
 */
function 摘关键词(原: string): string {
  const w = 原.replace(/[的了吗呢？?！!，,。\s]/g, "").slice(0, 12);
  return /^[过到起说讲提]+$/.test(w) ? "" : w;
}

/** 本月的起止，给 query_metric 用。按自然月，和「本月签约」那张卡口径一致 */
function 本月(): { from: string; to: string } {
  const d = new Date();
  const p = (n: number) => String(n).padStart(2, "0");
  const 年 = d.getFullYear();
  const 月 = d.getMonth() + 1;
  const 末 = new Date(年, 月, 0).getDate();
  return { from: `${年}-${p(月)}-01`, to: `${年}-${p(月)}-${p(末)}` };
}

