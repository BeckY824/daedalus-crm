/**
 * 意图直连：**把确定的事从模型手里拿走**。
 *
 * 「这个月谁签得最多」「有哪些渠道」「今天该跟谁」——这类问题的答案是一条**确定的查询**。
 * 让模型每次重新决定一遍，既慢（多一次决策往返，十几秒）又留着抖动的余地
 * （同一个问题今天选对、明天可能选错）。而业务逻辑和字段是固定的，本来就不该每次重新推理。
 *
 * 所以命中这张表的问题直接执行工具，模型只负责最后把数据说成人话——那一步它很稳。
 * 没命中的照常走 agent 循环（那条路要处理的是真正开放的问题）。
 *
 * **宁可漏，不可错。** 每条规则都要求足够具体：模糊的问句（「最近怎么样」）一律不匹配，
 * 让它去走循环。漏了只是慢一点，错了是答非所问。
 *
 * 加规则的依据不是拍脑袋：没命中的问题会记在日志里（run.ts 的 `[intent] 没命中`），
 * 照着真实问句加。
 */

