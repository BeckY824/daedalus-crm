export type 命中结果 = { 名: string; 调用: { name: string; args: Record<string, unknown> }[] };

/**
 * 这句话命中哪条规则。没命中返回 null——那才是 agent 循环存在的意义。
 *
 * **带了上文就不匹配**：「他呢？」「那这个月呢？」这类指代要靠模型解，
 * 而这张表只认完整问句。宁可漏。
 */
export type 页面范围 = { 表: string; 工具: string; 参数: string; 名字: readonly string[]; 筛选?: import("../ai-page-filters").页面客户筛选 };

/**
 * 「X 的电话 / 联系方式」——X 正列在当前页上时，直接用这一页的工具查 X。
 *
 * 这一条不在上面那张表里，因为它要看当前页：同一句「明杰哥的电话是多少」
 * 在渠道页该查渠道，在客户页该查客户，没有页面范围时谁也不该猜。
 * 2026-09-19 那一问就是这么错的：人站在渠道页，明杰哥就在表里的唯一一行，
 * 模型跑去客户库搜了个空，再让人「跟我说一声我按渠道那边查」。
 * 名字在这一页上、这一页是哪张表，两件事我们都确定知道，不该留给模型。
 *
 * 只认唯一命中：问的是「明」而表里有「明杰哥」「明月」，就落回模型。宁可漏。
 */
/**
 * 「X 的电话 / 联系方式 / 微信」——不管在哪一页，直接 find_person(X)。
 *
 * 这是那条页面版的推广。**人问一个人的联系方式时，用哪个工具是确定的**，
 * 不该每次让模型在十一个工具里挑：实测它这次挑了 search_customers、下次挑了
 * list_users（还把「李老师」截成「李」）。挑错不报错，只是答「没找到」。
 *
 * find_person 把五张有人名的表一起找，所以这里不需要知道 X 是客户还是渠道。
 * 只认「名字 + 联系方式词」这一种句式；多说一个字（「李老师的电话换了吗」）就落回模型。
 */
function 认要联系方式(q: string): 命中结果 | null {
  const m = q.match(/^(.{1,20}?)(?:的|得)?(?:联系电话|联系方式|手机号码|手机号|电话号码|电话|手机|号码|微信号|微信)(?:是多少|是什么|是啥|多少|是|呢)?[？?。！!\s]*$/);
  if (!m) return null;
  const x = m[1].trim();
  // 一个字的「李」谁都能沾上；空的更不行
  if (x.length < 2 || x.length > 10) return null;
  /*
    **名字那一段里不该有动词。** 没有这道闸时，「帮我记一笔今天和李四的电话」
    整句都命中：它以「电话」结尾，前面那截又正好在长度范围内，于是被当成
    一个叫「帮我记一笔今天和李四」的人——而那是一句**写入**请求，该走建议卡。
    这条是 tests/intents.test.ts 里原有的守卫抓出来的，不是想出来的。
  */
  if (/[帮记改把删加换设让请查看问和跟与，,、：:]/.test(x)) return null;
  return { 名: "某某的联系方式", 调用: [{ name: "find_person", args: { name: x } }] };
}

function 认页面上的一个(q: string, 范围?: 页面范围): 命中结果 | null {
  if (!范围 || 范围.名字.length === 0) return null;
  const m = q.match(/^(.{1,20}?)(?:的|得)?(?:联系电话|联系方式|手机号码|手机号|电话号码|电话|手机|号码|微信)(?:是多少|是什么|是啥|多少|是|呢)?[？?。！!\s]*$/);
  if (!m) return null;
  const x = m[1].trim();
  if (x.length < 2) return null;
  const 中 = 范围.名字.filter((n) => n === x || n.includes(x) || x.includes(n));
  if (中.length !== 1) return null;
  return { 名: `页面上的一个（${范围.表}）`, 调用: [{ name: 范围.工具, args: { [范围.参数]: 中[0] } }] };
}

export function 认意图(问题: string, 有上文 = false, 范围?: 页面范围): 命中结果 | null {
  const q = 问题.trim();
  if (!q || 有上文) return null;
  // 一句话里塞了两个问题（「有哪些渠道？另外这个月谁签得最多？」）交给模型，别只答一半
  if ((q.match(/[？?]/g) ?? []).length > 1) return null;
  // 站在某一页上时那条更准（直接查那一页那张表）；否则走跨表的 find_person
  const 页上 = 认页面上的一个(q, 范围) ?? 认要联系方式(q);
  if (页上) return 页上;
  for (const it of 意图表) {
    const m = q.match(it.配);
    if (!m) continue;
    const 调用 = it.工具.map((t) => ({ name: t.name, args: typeof t.args === "function" ? t.args(m, q) : t.args }));
    // 参数摘不出来（比如「谁提到过」后面是空的）就不算命中
    if (调用.some((c) => Object.values(c.args).some((v) => v === ""))) return null;
    return { 名: it.名, 调用 };
  }
  return null;
}
