/**
 * 同义词。
 *
 * 起因是一道真问题：用户问「谁提到过预算？」，而跟进记录里写的是「关注上岸率和**费用**」。
 * 字段再清楚也救不了这一步——这是两个词之间的距离，不是模型不懂表。
 *
 * 所以把它做成**确定的**：搜索类工具自己把同义词一起搜了，而不是指望模型想起来换个词。
 * 模型那边少一次判断，用户那边少一次「要不要换个词再搜一遍」的来回。
 *
 * 只收**业务上真的等价**的词。「价格」和「预算」在销售语境里指的是同一件事的两面，
 * 收进来；「意向」和「预算」不是，别收——同义词表一旦开始收「相关词」，
 * 搜什么都能搜出一堆，那比搜不到更糟。
 */

/** 一组里的词互为同义。全部小写比对，中文没有大小写问题，英文缩写有 */
const 组: string[][] = [
  ["预算", "费用", "学费", "价格", "多少钱", "报价"],
  ["试听", "体验课", "试课", "演示", "demo"],
  ["签约", "报名", "下单", "成交", "付款"],
  ["犹豫", "再想想", "考虑一下", "商量", "对比"],
  ["家长", "父母", "爸爸", "妈妈", "家里"],
  ["微信", "加微", "vx", "wx"],
  ["转介绍", "推荐", "介绍来的", "朋友介绍"],
  ["合同", "协议", "条款"],
  ["发票", "开票", "税号"],
  ["退费", "退款", "退课"],
];

/**
 * 一个关键词要搜哪些词：它自己 + 同组的其他词。
 * 不在表里就只搜它自己——**不猜**。
 */
export function 扩同义词(词: string): string[] {
  const w = 词.trim();
  if (!w) return [];
  const 命中 = 组.find((g) => g.some((x) => x === w || w.includes(x)));
  if (!命中) return [w];
  // 原词排第一：命中它的结果最该排在前面，也让调用方知道「用户问的是哪个」
  return [w, ...命中.filter((x) => x !== w)];
}

/** 这个词有没有同义词可扩。界面上要说清「我还替你搜了什么」时用 */
export function 有同义词(词: string): boolean {
  return 扩同义词(词).length > 1;
}
