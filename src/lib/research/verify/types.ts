/**
 * 背调的「真实性」那一块（2026-10-18，方案：Opensource_CRM/02-开发与发版/背调-真实性与补充信息-方案-20261018.md）。
 *
 * 和「合不合适」那 100 分完全分开：一项一盏灯，再给一盏总灯。**灯由代码按规则定**（rules.ts），模型改不了；
 * 模型只在下面写一句话总结。每一项的事实都对得回某个接口的返回（RDAP、工商库、制裁名单原文……），链接附在项上。
 *
 * 大部分项在我们的服务器上直查（/api/gateway/v1/research/verify，不经模型、不另扣次数）；
 * 「网上足迹」（LinkedIn / Facebook）在桌面端从搜索结果里认（social.ts），不打开那些页面。
 */

/** 灰 = 没提供 / 不适用 / 查不了：不是坏事，只是这一项没法下结论 */
export type 灯 = "green" | "yellow" | "red" | "gray";

/**
 * 这一项查成了什么样。只有前三种算「能核的项」（信息少的判断、总灯的「不到一半」都按它算）：
 *   已核    拿到了确定的答案（不管好坏：注册了 20 年、电话是英国手机、制裁名单没命中都算）
 *   没查到  查了，没有（工商库里没有、没找到官网、社媒全未搜到）
 *   查不了  对面的服务挂了、超时（不是这家公司的问题）
 *   没提供  要靠对方自报的东西（邮箱、电话、税号、邮件原文）没给
 *   不适用  这个国家没有能直查的官方库、没配 key 之类
 */
export type 核验态 = "已核" | "没查到" | "查不了" | "没提供" | "不适用";

export const 核验项表 = [
  { key: "registry", label: "工商登记" },
  { key: "vat", label: "税号" },
  { key: "domain", label: "域名" },
  { key: "site", label: "官网" },
  { key: "email", label: "邮箱" },
  { key: "phone", label: "电话" },
  { key: "ip", label: "邮件头" },
  { key: "sanctions", label: "制裁名单" },
  { key: "footprint", label: "网上足迹" },
] as const;
export type 核验键 = (typeof 核验项表)[number]["key"];

export type 核验链接 = { title: string; url: string };

export type 核验项 = {
  key: 核验键;
  灯: 灯;
  态: 核验态;
  /** 给人看的那一句事实，全由代码拼（接口返回的原样数据），不经模型 */
  事实: string;
  链接?: 核验链接[];
  /** 硬红的理由：总灯直接红（制裁疑似命中、仿冒域名、已注销、停放页） */
  硬红?: string;
  /** 域名注册不到 90 天：和「网上足迹全未搜到」凑在一起才算硬红（rules.ts） */
  新域名?: boolean;
};

/** 桌面端交给服务器核的东西。全是可选的：有什么核什么 */
export type 核验请求 = {
  runId: string;
  /** 公司名（登记名优先），拿去查工商库、制裁名单 */
  公司: string;
  /** 别的叫法（用户输入的那个名字和登记名不一样时），制裁名单、工商库两个都比 */
  别名?: string[];
  /** 官网域名（第一步认出来的），查注册时间、能不能打开 */
  域名?: string;
  /** 对方自报的邮箱（客户档案、用户那句话里带的） */
  邮箱?: string[];
  电话?: string[];
  /** 税号（VAT），带国家前缀，比如 DE123456789 */
  税号?: string;
  /** 国家：ISO 两位码（country.ts 认出来的） */
  国家?: string;
  /** 对方自报的国家（档案里填的），和电话归属国比 */
  自报国家?: string;
};

export type 核验回应 = {
  项: 核验项[];
  /** 制裁名单最近一次同步的时间（ISO） */
  名单更新于?: string;
};

export type 真实性 = {
  项: 核验项[];
  总灯: 灯;
  /** 总灯旁那一句，代码拼的：「基本可信，有 2 处要留意」 */
  总字: string;
  /** 模型写的一句话总结（不能改灯、不能改事实） */
  总结?: string;
  名单更新于?: string;
};
