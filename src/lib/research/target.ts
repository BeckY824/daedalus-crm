/**
 * 背调模式里那一句话，要查的是哪家（10-16 用户：「背调可以单独作为一个 agent……直接输入需求，就直接进入背调」）。
 *
 * 背调模式里发出去就开跑、要扣 1 次背调次数，所以**认不准的时候先别跑**：在卡片里让人点选或补一句，不扣次数。
 *   公司    认出一家：直接开跑
 *   候选    一句里说了好几家（「Rexel 和 Sonepar」）：让人点一家
 *   要补充  名字太短、太常见，很可能撞名（「SLV」「ABC」）：可以直接查，也可以补个国家或官网
 *   认不出  只有「这家公司」「他们」这种：让人输入公司名或官网
 * 只在本地按字面认，不调模型、不联网——这一步得是免费的。真正「是不是这一家」由背调第一步「认准公司」去核。
 */

export type 背调对象 =
  | { 种类: "公司"; 公司: string }
  | { 种类: "候选"; 候选: string[] }
  | { 种类: "要补充"; 公司: string; 原因: string }
  | { 种类: "认不出" };

/** 句首常见的说法：帮我查查 / 看看 / 背调一下 / 了解一下…… */
const 句首 = /^(?:请|帮我|帮忙|麻烦|给我|我想|想)?\s*(?:查一?查|查一下|查|看一?看|看一下|背调(?:一下)?|调查(?:一下)?|了解(?:一下)?|分析(?:一下)?|研究(?:一下)?|搜一?搜|搜一下)?\s*[:：]?\s*/;
/** 句尾的需求：适不适合我们、值不值得开发、怎么样…… 这些是需求，不是公司名。从最早出现的那个词截断 */
const 需求词 = ["哪家", "哪个", "适不适合", "合不合适", "值不值得", "怎么样", "靠不靠谱", "可不可靠", "能不能合作", "是什么公司", "是一家什么", "是做什么", "有没有风险", "好不好", "的背景", "的情况", "的底细", "这家公司", "这个公司", "这家", "背景"];
/** 单独出现时什么都指不了的词 */
const 空词 = /^(?:这家|这个|那家|他们|它|对方|客户|公司|这家公司|这个客户|一家公司|某公司)$/;

function 规整(s: string): string {
  return s.replace(/^[「『“"'《\s]+|[」』”"'》\s。.!！?？]+$/g, "").trim();
}

export function 认背调对象(原话: string): 背调对象 {
  const t = 原话.trim();
  if (!t) return { 种类: "认不出" };

  // 给了网址 / 域名：最准的线索，直接按它查
  const 网址 = t.match(/(?:https?:\/\/)?(?:www\.)?([a-z0-9-]+(?:\.[a-z0-9-]+)*\.[a-z]{2,})(?:\/\S*)?/i);
  if (网址 && /\.[a-z]{2,}$/i.test(网址[1]) && !/@/.test(网址[0])) return { 种类: "公司", 公司: 网址[1].toLowerCase() };

  // 去掉句首的「帮我查」和句尾的需求，剩下的是对象
  let 主体 = t.replace(句首, "");
  主体 = 主体.split(/[，,。；;\n]/)[0] ?? "";
  const 截 = 需求词.map((w) => 主体.indexOf(w)).filter((i) => i > 0);
  if (截.length) 主体 = 主体.slice(0, Math.min(...截));
  主体 = 规整(主体);

  // 一句里说了好几家
  const 几家 = 主体
    .split(/\s*(?:、|\band\b|\bvs\.?\b|\bor\b|和|与|还是)\s*/i)
    .map(规整)
    .filter((x) => x.length >= 2 && !空词.test(x));
  if (几家.length > 1) return { 种类: "候选", 候选: [...new Set(几家)].slice(0, 5) };

  if (主体.length < 2 || 空词.test(主体) || 主体.length > 120) return { 种类: "认不出" };
  // 名字太短（全大写的三四个字母、或两三个字的中文简称）：同名的公司太多，先提醒一句
  if (/^[A-Z0-9&.]{2,4}$/.test(主体) || /^[一-鿿]{2,3}$/.test(主体)) {
    return { 种类: "要补充", 公司: 主体, 原因: `「${主体}」这个名字很短，同名的公司可能很多。补一个国家或官网会认得更准` };
  }
  return { 种类: "公司", 公司: 主体 };
}
