/**
 * 首页这一句是不是「帮我背调 XX」，是的话 XX 是谁。
 *
 * 认出来就不走 agent（那条路一问扣 1 次、也没有搜索工具），直接出背调的确认卡；
 * 认不出来照常当问题问——宁可漏认，也不要把「背调要多少钱」这种问题当成要背调一家叫「要多少钱」的公司。
 * 所以只认「背调」这个词明确出现、而且能摘出一个像公司名的东西的句子。
 */

/** 句尾常带的话：「…，看值不值得开发」「这家公司」「一下」 */
const 尾巴 = /(这家公司|这个公司|这家|公司的?背景|的背景|的情况|一下|吧|呢)$/;

function 收(x: string): string | null {
  let s = x.split(/[，,。！!？?；;\n]/)[0].trim();
  s = s.replace(/^[「『“"'《]+|[」』”"'》]+$/g, "").trim();
  for (let i = 0; i < 3; i++) s = s.replace(尾巴, "").trim();
  s = s.replace(/^[「『“"'《]+|[」』”"'》]+$/g, "").trim();
  // 太短、太长、或者只剩疑问词的，不像公司名
  if (s.length < 2 || s.length > 120) return null;
  if (/^(什么|怎么|多少|哪些|哪家|是|的|要|能|会|可以|功能|次数|价格|费用|多久)/.test(s)) return null;
  // 「帮我背调」后面什么都没有：前缀被当成了公司名
  if (/^(请|帮我|帮忙|给我|麻烦|对|把|给)$/.test(s)) return null;
  return s;
}

export function 认背调意图(question: string): string | null {
  const q = question.trim();
  if (!/背调/.test(q)) return null;
  // 「帮我背调一下 X」「背调 X」「请背调：X」「做个背调：X」
  const 前 = q.match(/^(?:请|帮我|帮忙|给我|麻烦)?\s*(?:做(?:个|一个|一次|一下)?)?\s*背调(?:一下|下)?\s*[:：]?\s*(.+)$/);
  if (前) return 收(前[1]);
  // 「X 背调一下」「对 X 做个背调」「帮我把 X 背调一下」
  const 后 = q.match(/^(?:请|帮我|帮忙|给我|麻烦)?\s*(?:对|把|给)?\s*(.+?)\s*(?:做(?:个|一个|一次|一下)?)?\s*背调(?:一下|下)?[。.!！]?$/);
  if (后) return 收(后[1]);
  return null;
}
