/**
 * 「你为什么只有 3 次」这句话，只此一份。
 *
 * 背景：注册赠送那 30 次**一台电脑只发一次**（lib/tenant/credits.ts）。
 * 同一台电脑上的第二个账号登录后就只有每日的那几次，而在 0.40.0 之前，
 * 界面上没有任何地方说得出原因——注册页写着「送 30 次」，设置页显示「还剩 3 次」，
 * 中间那句话谁都没说。用户只会认为是个 bug。
 *
 * 为什么单独一个文件：要说这句话的地方有两处（设置页的「桌面端」栏和「AI 接入」栏），
 * 而它们一个在客户端渲染、一个也在客户端，都够不到 lib/llm.ts 那些服务端依赖。
 * 抄两遍的下场是改了一处、另一处还在说旧话。
 *
 * **不知道就什么都不说。** `注册赠送已发` 是 undefined 时（老版本服务端不返回这个字段）
 * 返回 null——猜一句解释挂在那儿，比不解释更糟。
 *
 * 0.46.6 起每日赠送只发注册后 30 天：期内带上「到哪天为止」，过了期明说已经结束。
 * 过期时服务端把 `每日赠送` 报成 0，所以老服务端 / 老客户端两头都不会许诺一个不再发的赠送。
 */
export function 赠送说明(余额: {
  每日赠送?: number;
  注册赠送?: number;
  注册赠送已发?: boolean;
  每日赠送截至?: string | null;
} | null | undefined): string | null {
  if (!余额) return null;
  const 截至 = 余额.每日赠送截至 ? 月日(余额.每日赠送截至) : null;
  // 期内：「每天登录再送 3 次（到 10 月 27 日）」；不知道截至就照老样子说
  const 每日句 = 余额.每日赠送 ? `每天登录再送 ${余额.每日赠送} 次${截至 ? `（到 ${截至}）` : ""}` : null;
  const 过期句 = !余额.每日赠送 && 截至 ? `注册后 30 天的每日赠送已在 ${截至}结束` : null;
  const 每日 = 每日句 ?? 过期句;
  if (余额.注册赠送已发 === false) {
    const 送 = 余额.注册赠送;
    return (
      `没有开户赠送的那${送 ? ` ${送} ` : ""}次：${送 ? `那 ${送} 次` : "它"}一台电脑只送一份，` +
      `这台电脑上已经有别的账号领过了` +
      (每日句 ? `。${每日句.replace("每天登录", "每天登录仍然")}` : 过期句 ? `；${过期句}` : "")
    );
  }
  return 每日;
}

/** "2026-10-27" → "10 月 27 日"。不是这个形状就原样返回，别把一个看不懂的值说成日期 */
function 月日(日: string): string {
  const m = /^\d{4}-(\d{2})-(\d{2})$/.exec(日);
  return m ? `${Number(m[1])} 月 ${Number(m[2])} 日` : 日;
}
