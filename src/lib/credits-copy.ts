/**
 * 「你为什么只有 3 次」这句话，只此一份。
 *
 * 背景：注册赠送那 30 次**一台电脑只发一次**（lib/tenant/credits.ts）。
 * 同一台电脑上的第二个账号登录后一次免费的都没有（0.46.15 前还有每日的那几次），而在 0.40.0 之前，
 * 界面上没有任何地方说得出原因——注册页写着「送 30 次」，设置页显示「还剩 3 次」，
 * 中间那句话谁都没说。用户只会认为是个 bug。
 *
 * 为什么单独一个文件：要说这句话的地方有两处（设置页的「桌面端」栏和「AI 接入」栏），
 * 而它们一个在客户端渲染、一个也在客户端，都够不到 lib/llm.ts 那些服务端依赖。
 * 抄两遍的下场是改了一处、另一处还在说旧话。
 *
 * **不知道就什么都不说。** `注册赠送已发` 是 undefined 时（老版本服务端不返回这个字段）
 * 返回 null——猜一句解释挂在那儿，比不解释更糟。
 *
 * **0.46.15（2026-10-03）起没有每日赠送了，只送开户那 30 次**：这里不再说「每天登录再送」，
 * 老服务端还报着的 每日赠送 / 每日赠送截至 也一概不理（新服务端恒报 0 和 null）。
 */
export function 赠送说明(余额: {
  每日赠送?: number;
  注册赠送?: number;
  注册赠送已发?: boolean;
  每日赠送截至?: string | null;
} | null | undefined): string | null {
  if (!余额) return null;
  const 送 = 余额.注册赠送;
  if (余额.注册赠送已发 === false) {
    return (
      `免费次数一台电脑只送一份${送 ? `（开户 ${送} 次）` : ""}，这台电脑上已经有别的账号领过了。` +
      `要用 AI，在「设置 → AI 接入」填自己的 Key 就行，不限次数`
    );
  }
  // 10-03 起只送开户那一份、用完不补：说一句，免得人以为明天还会有
  if (余额.注册赠送已发 === true && 送) return `开户送的 ${送} 次用完就不再补了；在「设置 → AI 接入」填自己的 Key，不限次数`;
  return null;
}

