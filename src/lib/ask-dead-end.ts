/**
 * 这一问是不是白问了，以及给他一条不花钱的活路。
 *
 * **单人桌面端一天只有 3 次免费提问**（注册赠送 30 次一台电脑只发一次，
 * 之后每天补 3 次，见 lib/tenant/credits.ts）。所以一句「没查到，你给个更完整的
 * 姓名我再查一次」不是慢一点的问题——它当场吃掉当天三分之一的额度，
 * 而且把人留在一个死胡同里：他只能再问一次，再烧一次。
 *
 * 认出这种回答之后，界面上给一条**不走模型**的路：直接去列表页搜那个词。
 * 那条路一次额度都不花，而且多半就能看见他要的东西。
 *
 * 纯函数，不引 next 也不碰库——判据要能一条条钉在用例上。
 */

/** 回答里出现这些说法，基本就是没答上来 */
const 没答上来的说法 = [
  "没找到",
  "没有找到",
  "没查到",
  "查不到",
  "没有匹配",
  "查无此人",
  "没有这个人",
  "不存在",
  "没有登记",
  "更完整的姓名",
  "更完整的名字",
  "再查一次",
];

/**
 * 从问句里摘出那个要搜的词。
 *
 * 只认「X 的电话 / X 是谁 / 找一下 X」这几种把名字摆在明面上的句式——
 * **摘不出来就返回空，界面上那条路就不出现**。摘错一个词，
 * 把人送到一个搜「的」的列表页，比不给这条路更糟。
 */
export function 摘要搜的词(问题: string): string {
  const q = 问题.trim().replace(/[？?。！!\s]+$/, "");
  const 句式 = [
    /^(.{2,10}?)(?:的|得)?(?:联系电话|联系方式|手机号码|手机号|电话号码|电话|手机|号码|微信号|微信)(?:是多少|是什么|是啥|多少|是|呢)?$/,
    /^(.{2,10}?)(?:是谁|是哪位|什么情况|怎么样了|是哪家公司的|在哪家公司)$/,
    /^(?:找一下|找找|查一下|搜一下|看看)(.{2,10}?)(?:的资料|的情况|的记录)?$/,
  ];
  for (const re of 句式) {
    const m = q.match(re);
    if (m?.[1]) {
      /*
        末尾那个「的」要削掉再判长度。捕获组最少吃两个字，所以「李的电话是多少」
        会捕到「李的」——两个字，门槛放它过去，于是人被送去搜一个不存在的「李的」。
        削完剩一个字，下面那道两字门槛才真正拦得住。
      */
      const x = m[1].trim().replace(/[的得]$/, "");
      // 动词混进来就当没摘到，和 intents.ts 那条同一个道理
      if (x.length >= 2 && !/[帮记改把删加换设让请和跟与，,、：:]/.test(x)) return x;
    }
  }
  return "";
}

export type 死胡同 = { 词: string } | null;

/**
 * @param 回答   模型最终说的那段话
 * @param 问题   人问的原话
 * @param 查过几次工具 这一轮真的调用过几个工具。0 表示它一条数据都没查就答了
 */
export function 认死胡同(回答: string, 问题: string, 查过几次工具: number): 死胡同 {
  const t = (回答 ?? "").trim();
  if (!t) return null;
  // 查过东西、而且没说「没找到」——那就是正常回答
  const 说了没有 = 没答上来的说法.some((x) => t.includes(x));
  if (!说了没有 && 查过几次工具 > 0) return null;
  const 词 = 摘要搜的词(问题);
  if (!词) return null;
  return { 词 };
}
