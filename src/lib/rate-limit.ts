/**
 * 登录失败限流。
 *
 * 系统直接挂在公网 IP 上，没有任何频率限制的话，撞库脚本可以不限速地试密码。
 *
 * **刻意不做「账号锁定」**：锁定看起来更严，但会引入一个更容易发生的问题——
 * 任何人只要拿别人的用户名连试几次，就能把同事锁在系统外面，
 * 而这套系统只有几个人用，一个人被锁住就是一个人干不了活。
 * 改成短时冷却：连续失败到阈值后拒绝一段时间，时间一到自动恢复，
 * 成功登录立即清零。挡得住脚本，挡不住的只有「等几分钟再试」的人，
 * 而那已经不是撞库的速度了。
 *
 * 状态放内存：只有一个容器，重启即清空。这是可接受的——
 * 重启不是攻击者能触发的动作，而为它引一张表、一个 Redis 都不划算。
 */

type 记录 = { 失败次数: number; 冷却到: number };

const 桶 = new Map<string, 记录>();

/** 多久没再失败就把计数忘掉 */
const 记忆毫秒 = 15 * 60 * 1000;

/**
 * Map 的条数上限。
 *
 * 这张表只增不减，而 key 里含来源 IP。即便 IP 已经改成取不可伪造的那一段，
 * 也不该让一张进程内的表无上限长下去——真被人换着账号名慢速试，
 * 每个不存在的账号都会占一条。超过上限就先清掉过期的，还不够就按插入顺序
 * 丢最早的（Map 保序）。丢掉的最坏后果是某个 key 的失败计数重新从 0 开始，
 * 而攻击者并不能选择丢谁，所以不构成绕过手段。
 */
export const 最多条数 = 10_000;

function 控制体积(now: number) {
  if (桶.size <= 最多条数) return;
  for (const [k, r] of 桶) {
    if (r.冷却到 && r.冷却到 + 记忆毫秒 < now) 桶.delete(k);
  }
  while (桶.size > 最多条数) {
    const 最早 = 桶.keys().next();
    if (最早.done) break;
    桶.delete(最早.value);
  }
}

/**
 * 阈值分两档，因为两种 key 的误伤代价完全不同。
 *
 * **按账号**：5 次。针对某一个账号的撞库，5 次足够挡住，
 * 而误伤只落在打错密码的本人头上。
 *
 * **按 IP**：30 次。整个办公室共用一个出口 IP，
 * 阈值定得和账号一样的话，一个同事打错 5 次就把全公司挡在外面 5 分钟——
 * 这比它防的问题更糟。定高一档，只拦真正在批量试的脚本，
 * 人正常犯错永远碰不到。
 */
export const 阈值 = 5;
export const IP阈值 = 30;
/** 冷却多久（毫秒） */
export const 冷却毫秒 = 5 * 60 * 1000;


/**
 * 从 X-Forwarded-For 里取出**不可伪造**的那一段。
 *
 * XFF 是一条链：`客户端自称的, 上游代理看到的, ..., 最近一跳看到的`。
 * 前面几段都是客户端能自己写的——取第一段的话，攻击者每次换个假 IP
 * 就换一个限流桶，IP 档的上限形同虚设，还能用假 IP 把内存里的表撑大。
 * 最后一段是紧邻的反代（这里是 Caddy）自己拼上去的，伪造不了。
 *
 * 没有这个头说明没走反代，返回 null：那种情况下任何 IP 都是客户端说了算，
 * 按它限流没有意义，只按账号限即可。
 */
export function 解析来源IP(xff: string | null | undefined): string | null {
  if (!xff) return null;
  const 段 = xff.split(",").map((x) => x.trim()).filter(Boolean);
  return 段.length ? 段[段.length - 1] : null;
}

/** 当前记录条数，供测试观察体积控制是否生效 */
export function 当前条数() {
  return 桶.size;
}

/** 测试用：清空所有计数 */
export function 重置限流() {
  桶.clear();
}

/**
 * 检查这个 key 现在能不能试。
 * 返回 null 表示放行；否则返回还要等多少秒。
 */
export function 检查限流(key: string, now = Date.now()): number | null {
  const r = 桶.get(key);
  if (!r) return null;
  if (r.冷却到 > now) return Math.ceil((r.冷却到 - now) / 1000);
  // 冷却已过，且很久没再失败，就当没发生过
  if (r.冷却到 && r.冷却到 + 记忆毫秒 < now) 桶.delete(key);
  return null;
}

/** 记一次失败，达到阈值就进入冷却 */
export function 记一次失败(key: string, now = Date.now(), 本档阈值 = 阈值) {
  const r = 桶.get(key) ?? { 失败次数: 0, 冷却到: 0 };
  // 上一轮冷却早就过去了，从头算
  if (r.冷却到 && r.冷却到 + 记忆毫秒 < now) {
    r.失败次数 = 0;
    r.冷却到 = 0;
  }
  r.失败次数 += 1;
  if (r.失败次数 >= 本档阈值) {
    r.冷却到 = now + 冷却毫秒;
    r.失败次数 = 0; // 冷却结束后重新计数，而不是一直卡着
  }
  桶.set(key, r);
  控制体积(now);
}

/** 登录成功，立即清零 */
export function 清除限流(key: string) {
  桶.delete(key);
}
