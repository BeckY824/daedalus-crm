/** 用哪套：服务端传 企业版()，界面传服务端给的 企业版 */
export function 字典of(企业版: boolean): 阶段字典 {
  return 企业版 ? 企业版字典 : 团队版字典;
}

/** 一个阶段在对方表里的全部值：节点 + 两个出口（出口有原文按原文） */
export function 阶段值们(字典: 阶段字典, s: 阶段): string[] {
  return [...字典.节点们[s], ...字典.出口们[s].map((o) => o.原文 ?? o.叫法)];
}

/** 结局在界面上的叫法（企业版线索流失、丢单都叫「流失」）；认不出的原样 */
export function 结局叫法(r: string, 字典: 阶段字典 = 团队版字典): string {
  for (const s of 阶段们) for (const o of 字典.出口们[s]) if (o.结局 === r) return o.叫法;
  return r;
}

/** 按团队版写的节点名对到这套（企业版 验收交付 → 交付验收）；不用改名的原样 */
export function 本套节点名(node: string, 字典: 阶段字典): string {
  return 字典.改名[node] ?? node;
}
