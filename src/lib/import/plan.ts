/**
 * 二维表 + 列映射 → 每一行打算写什么、哪一格有问题。
 *
 * 纯函数，不碰数据库。查重、渠道解析、真正落库在 import-actions.ts 里。
 *
 * **一条贯穿全文件的分寸：逐格留空，不整行拒绝。**
 * 一行里有一个日期格式看不懂，不该让这个人整条进不来——把那一格留空、标出来，
 * 其余字段照进。整行拒绝的代价是人要回 Excel 里改完再导一遍，
 * 而他多半根本不知道是哪一格的事。
 *
 * 只有两种情况整行进不了，都和「认人」有关：没有手机号、手机号不像个号码。
 * 手机号是这套库里认人的唯一依据（schema 里 Customer.phone 的注释就是「查重主键」），
 * 没有它这一行既不知道是谁、也没法判断是不是已经有了。
 */
import type { 字段名, 字段规格 } from "./fields";
import { 规整手机号, 像手机号, 号码带着字 } from "../phone";

/** 照收：值不在选项里，但这个字段是开放的，原样写进去（不是问题，是提示） */
export type 严重程度 = "拦行" | "留空" | "用默认" | "照收";

export type 格问题 = {
  /** 第几列（从 0 数，对应表头数组的下标） */
  列: number;
  字段: 字段名;
  原值: string;
  /** 给人看的一句话 */
  说法: string;
  严重: 严重程度;
};

export type 一行 = {
  /** 在原表里的行号，1 是表头，所以第一条数据是 2——报错时人要照着这个数去 Excel 里找 */
  行号: number;
  值: Partial<Record<字段名, string>>;
  问题: 格问题[];
  /** 有值 = 这一行整条进不了，这句话就是原因 */
  进不了?: string;
  /**
   * 「表头：值」并进备注的那几行（没对上的列、封闭枚举落默认的原文）。值.remark 里已经含着它们；
   * 单独留一份是给「库里已有、只补空」那条路：库里备注有值时，对上「备注」的那列照旧不动，
   * 这几行我们没有地方放的原话添在库里备注后面，不然整列丢（2026-10-04 L-004）
   */
  并进备注?: string[];
};

/**
 * 手机号的规整与「像个号码」挪到了 lib/phone.ts：客户表单和 saveCustomer 也要用同一条规矩
 * （2026-09-28 审查 S2：表单用大陆手机号正则，导进来的海外号 / 座机一编辑就卡住）。
 * 这里转出去，老的引用不用改。
 */
export { 规整手机号, 像手机号 };

/**
 * Excel 的日期有三种面孔，都要认：
 *   1. 文本：`2026-09-19`、`2026/9/19`、`2026年9月19日`
 *   2. 序列号：`46000`（1900 年 1 月 0 日起的天数，Excel 自己的存法）
 *   3. 浏览器里解析 xlsx 时已经变成的 ISO 串
 *
 * 认不出来返回 null，由调用方把那一格留空并标出来——**绝不猜**。
 * 猜错一个预计签约日期，人会照着它去安排下周的工作。
 */
export function 认日期(v: string): Date | null {
  const s = v.trim();
  if (!s) return null;
  // 8 位连写的 20260919（不少系统这么导，第二轮 r2-data）。年份 1900–2100、月日合法才认，否则往下当序列号 / 别的
  const 连写 = /^(19\d{2}|20\d{2}|2100)(\d{2})(\d{2})$/.exec(s);
  if (连写) {
    const [y, mo, d] = [Number(连写[1]), Number(连写[2]), Number(连写[3])];
    const dt = new Date(y, mo - 1, d);
    if (dt.getMonth() === mo - 1 && dt.getDate() === d) return dt;
  }
  // Excel 序列号。25569 = 1970-01-01；小于它的当不是日期（那更可能是个数量）
  if (/^\d{4,6}(\.\d+)?$/.test(s)) {
    const n = Number(s);
    if (n < 25569 || n > 80000) return null;
    const ms = Math.round((n - 25569) * 86400 * 1000);
    const u = new Date(ms);
    if (isNaN(u.getTime())) return null;
    /*
      **落成本地时间的零点，不是 UTC 零点。**

      序列号算出来的是 UTC 时刻，而下面文本那条路走的是 `new Date(y, m, d)`，
      落的是本地零点。两条路不统一的话，同一个「2026-09-19」经由 xlsx 和经由 csv
      进来会差几个小时——在 UTC 以西的时区里就直接差一天，界面上显示成前一天，
      而两边都没有任何报错。日期只用来看「哪一天」，时分秒没有意义。
    */
    return new Date(u.getUTCFullYear(), u.getUTCMonth(), u.getUTCDate());
  }
  const 规整 = s
    .replace(/[年月]/g, "-")
    .replace(/日/g, "")
    .replace(/\./g, "-")
    .replace(/\//g, "-")
    .replace(/-+$/, "");
  const m = /^(\d{4})-(\d{1,2})-(\d{1,2})/.exec(规整);
  if (m) {
    const [, y, mo, d] = m;
    const dt = new Date(Number(y), Number(mo) - 1, Number(d));
    // 2026-02-31 会被 Date 滚到 3 月 3 日。滚过头就说明这个日期不存在
    if (dt.getMonth() !== Number(mo) - 1 || dt.getDate() !== Number(d)) return null;
    return dt;
  }
  return null;
}

/**
 * 枚举值对齐：完全相等最好，其次去掉空白再比。
 *
 * **不做近似匹配。** 「已联系」和「已加微信」编辑距离很近，但意思差得远，
 * 而跟进状态是拿来筛人、排工作的。对不上就用默认值 + 标出来，让人在复核那一步
 * 自己指一下——那一步里同一个写法改一次，整列一起生效，不比猜慢。
 */
export function 认枚举(v: string, values: readonly string[]): string | null {
  const s = v.trim();
  if (!s) return null;
  const hit = values.find((x) => x === s);
  if (hit) return hit;
  const 紧 = s.replace(/[\s　]/g, "");
  return values.find((x) => x.replace(/[\s　]/g, "") === 紧) ?? null;
}

export type 排布 = {
  表头: string[];
  数据: string[][];
  /**
   * 库里有的渠道名。给了就当场对：对不上的那一格留空、原文并进备注、预览里标出来。
   * 不给（纯函数测试、老调用）就照旧原样收下，留给落库那一步。
   */
  认得的渠道?: Set<string>;
  /** 每一列对到哪个字段，null = 这列不导 */
  映射: (字段名 | null)[];
  字段表: 字段规格[];
  /**
   * 对不上任何字段的那几列怎么办。
   *
   * 这是导入里最常见的一种落差：人手上那份表有「微信号」「身份证」「客户等级」
   * 「年营收」这些我们没有的列。自定义字段是明确不做的（那是另一个产品），
   * 于是只有两条路：**丢掉**，或者**并进备注**。
   *
   * 默认是并进备注，因为丢掉是不可见的损失——人以为整份表都进来了，
   * 几周后才发现微信号一个都没有，而那时原表可能已经改过了。
   * 并进备注至少让那些字还在这个人身上，能搜得到。
   */
  没对上的列?: "并进备注" | "丢掉";
  /**
   * 人在复核那一步改过的值：`列|原值` → 改成什么。
   * 键里带列号，因为同一个词在不同列里的意思不同
   * （「其他」在年级列和在跟进状态列是两个值）。
   */
  改过?: Record<string, string>;
};

/** 复核那一步的修改键。导出出来是为了界面和这里用的是同一把钥匙，别各拼各的 */
export function 改动键(列: number, 原值: string): string {
  return `${列}|${原值}`;
}

/**
 * 把整张表摊成一行一行的结果。
 *
 * 这是导入的心脏：预览上那四个数、复核那一屏列的问题、真正落库时写什么，
 * 全部从这一个函数的结果里读。**不许有第二处算同样的东西**——
 * 预览说「新建 30 条」而实际建了 28 条，这种事只会发生在两处各算一遍的时候。
 */
export function 摊开(p: 排布): 一行[] {
  const 规格 = new Map(p.字段表.map((f) => [f.名, f]));
  return p.数据.map((r, i) => {
    const 行号 = i + 2;
    const 值: Partial<Record<字段名, string>> = {};
    const 问题: 格问题[] = [];
    /** 封闭枚举对不上、落成默认值的那几列。原文要并进备注，见下面 */
    const 落默认的列 = new Set<number>();

    p.映射.forEach((字段, 列) => {
      if (!字段) return;
      const f = 规格.get(字段);
      if (!f) return;
      const 原值 = (r[列] ?? "").trim();
      const 改成 = p.改过?.[改动键(列, 原值)];
      const v = 改成 !== undefined ? 改成 : 原值;
      if (!v) return;

      if (字段 === "phone") {
        const n = 规整手机号(v);
        if (!像手机号(n)) {
          问题.push({ 列, 字段, 原值: v, 说法: v.includes("*") ? "这是打了码的号码，认不了人" : "这不像一个电话号码", 严重: "拦行" });
          return;
        }
        值.phone = n;
        // 「13800001111（微信同号）」：号码取出来，原文并进备注
        if (号码带着字(v)) {
          问题.push({ 列, 字段, 原值: v, 说法: `电话按 ${n} 导入，原文并进备注`, 严重: "照收" });
          落默认的列.add(列);
        }
        return;
      }
      if (f.kind === "enum") {
        const hit = 认枚举(v, f.values ?? []);
        if (!hit) {
          /*
            开放的枚举（职位 / 年级）：对不上就**原样收下**，不丢。
            库里这一列本来就是自由文本，那张下拉表只是界面上的建议；
            而人手上那份表里的职位千奇百怪，丢掉等于档案缺一块，
            他当时只看到一行灰字，事后才发现。

            封闭的那两个（跟进状态 / 决策状态）照旧用默认值——它们被盯盘、
            建议卡、报表分组吃着，塞一个没人认识的值进去会静悄悄打乱统计。
          */
          if (f.开放) {
            值[字段] = v;
            问题.push({ 列, 字段, 原值: v, 说法: `「${v}」不在${f.label}的选项里，会按原样导入`, 严重: "照收" });
            return;
          }
          问题.push({ 列, 字段, 原值: v, 说法: `「${v}」不是${f.label}里的值，这一格会用默认值，原文并进备注`, 严重: "用默认" });
          落默认的列.add(列);
          return;
        }
        值[字段] = hit;
        return;
      }
      if (f.kind === "date") {
        const d = 认日期(v);
        if (!d) {
          问题.push({ 列, 字段, 原值: v, 说法: `「${v}」读不出是哪一天，这一格会留空`, 严重: "留空" });
          return;
        }
        值[字段] = d.toISOString();
        return;
      }
      /*
        来源渠道要对到库里的渠道。原来这里原样收下、落库时对不上就记 null，**不报也不进备注**——
        而「来源」是它的别名，人表里的「来源」多半写「官网 / 展会 / 转介绍」，渠道表里存的却是人名，
        于是整列悄悄没了（2026-10-02 排查）。调用方给了库里的渠道名单就当场对。
      */
      if (字段 === "channelName" && p.认得的渠道 && !p.认得的渠道.has(v)) {
        问题.push({ 列, 字段, 原值: v, 说法: `库里没有叫「${v}」的渠道，这一格留空，原文并进备注`, 严重: "用默认" });
        落默认的列.add(列);
        return;
      }
      // text：原样收下
      值[字段] = v;
    });

    /*
      对不上任何字段的那几列：默认并进备注，写成「表头：值」一行一条。

      **不做自定义字段**（那是另一个产品，ROADMAP 里明确不做），
      但也不能默不作声地丢掉——人以为整份表都进来了，几周后才发现
      微信号一个都没有，而那时原表可能已经改过了。
      并进备注至少让那些字还在这个人身上，搜得到。
    */
    /*
      封闭枚举（跟进状态 / 决策状态）对不上时，字段里用默认值，**原文也并进备注**。

      否则这就是「一个字都不丢」里最安静的那个洞：人把一列对到了跟进状态，
      复核那一屏每格都写着「用默认值」，他点了下一步，那一整列原话就没了。
      这一条**不看「没对上的列」那个开关**——开关问的是「我们没有的列要不要」，
      而这一列人是明确要的，只是值我们收不下。用的是表里的原文，不是复核时改成的值
      （改成了合法值就不会走到这里）。
    */
    const 并备注 = (p.没对上的列 ?? "并进备注") === "并进备注";
    const 捡回来: string[] = [];
    p.映射.forEach((字段, 列) => {
      if (字段 ? !落默认的列.has(列) : !并备注) return;
      /*
        对上了字段的那列表头是空的也有出处：用字段名当表头。
        没对上、又没有表头的列（表头只写了前两列、后面几格空着）用「第 N 列」当出处：
        原来直接丢——「一串没出处的值比丢掉还糟」，可丢掉的是人表里的原话，他事后回原表才知道少了什么；
        写成「第 3 列：北京」，人照着列号回 Excel 里一眼对得上（2026-10-04 J-056）
      */
      const 头 = (p.表头[列] ?? "").trim() || (字段 ? 规格.get(字段)?.label ?? "" : `第 ${列 + 1} 列`);
      const v = (r[列] ?? "").trim();
      if (!头 || !v) return;
      /*
        表头看着是日期、格子是 Excel 序列号（46284）的：写成日期再并进去。原来备注里是「最近联系：46284」，
        人看不懂（第一轮 2-7、第二轮又见）
      */
      const 像日期列 = /日期|时间|生日|日$/.test(头) && /^\d{5}(\.\d+)?$/.test(v);
      const d = 像日期列 ? 认日期(v) : null;
      const 写 = d ? `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}` : v;
      捡回来.push(`${头}：${写}`);
    });
    if (捡回来.length > 0) {
      值.remark = 值.remark ? `${值.remark}\n${捡回来.join("\n")}` : 捡回来.join("\n");
    }

    // 认人那两格。顺序要紧：先说没有手机号，再说姓名——手机号是认人的那一列
    let 进不了: string | undefined;
    if (!值.phone) {
      const 有格问题 = 问题.some((q) => q.字段 === "phone");
      进不了 = 有格问题 ? "手机号看不出是个号码" : "这一行没有手机号";
    } else if (!值.name) {
      进不了 = "这一行没有姓名";
    }
    return { 行号, 值, 问题, ...(进不了 ? { 进不了 } : {}), ...(捡回来.length ? { 并进备注: 捡回来 } : {}) };
  });
}

/**
 * 备注末尾添几行：已经在备注里的那一行不再添（同一份表导两遍、同号两行写了同一句，都不该出现两遍）。
 * 原来的字一个不动，只往后加（2026-10-04 J-051）。
 */
export function 添行(原: string | null | undefined, 新行: readonly string[]): string {
  const 有 = new Set((原 ?? "").split("\n").map((l) => l.trim()).filter(Boolean));
  const 要添: string[] = [];
  for (const l of 新行) {
    const t = l.trim();
    if (!t || 有.has(t)) continue;
    有.add(t);
    要添.push(l);
  }
  if (要添.length === 0) return 原 ?? "";
  return 原 ? `${原}\n${要添.join("\n")}` : 要添.join("\n");
}

/**
 * 同一份表里手机号重复的行：后面的补前面的空，合成一条。
 *
 * Attio 那边把这件事写在预览里叫「最多创建 X 条」——真正执行时同一唯一值的多行会合并。
 * 我们直接在预览之前就合掉，预览上那个数就是真实会发生的数：
 * **人看到的数和事后的结果不一致，比数大一点更伤信任。**
 *
 * 合并方向是「先来的赢」：第一次出现的那行是主，后面几行只填它没填的格。
 * 反过来（后来的覆盖）意味着表格末尾一个残缺的补录行能抹掉前面完整的那条。
 */
export function 并重复行(rows: 一行[]): { 行: 一行[]; 合掉几行: number } {
  const 按号: Map<string, 一行> = new Map();
  const 出: 一行[] = [];
  let 合掉几行 = 0;
  for (const r of rows) {
    if (r.进不了 || !r.值.phone) {
      出.push(r);
      continue;
    }
    const 已有 = 按号.get(r.值.phone);
    if (!已有) {
      按号.set(r.值.phone, r);
      出.push(r);
      continue;
    }
    for (const [k, v] of Object.entries(r.值)) {
      /*
        备注例外：它是越记越多的那一格，后一行的备注（连同并进来的「微信号：…」）添在后面，不是「前面有了就整段丢」。
        原来第一行有备注，第二行的整段备注、没对上的列一个字都不进，预览也不说（2026-10-04 J-051）。
        其余字段照旧先来的赢
      */
      if (k === "remark") {
        if (v) 已有.值.remark = 添行(已有.值.remark, v.split("\n"));
        continue;
      }
      if (v && !已有.值[k as 字段名]) 已有.值[k as 字段名] = v;
    }
    if (r.并进备注?.length) 已有.并进备注 = [...(已有.并进备注 ?? []), ...r.并进备注];
    已有.问题.push(...r.问题);
    合掉几行++;
  }
  return { 行: 出.filter((r) => r.进不了 || 按号.get(r.值.phone ?? "") === r), 合掉几行 };
}
