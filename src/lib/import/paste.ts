/**
 * 「粘任何东西」：一段没有格式的文本 → 和 Excel 那条路一模一样的二维表。
 *
 * 人手上的名单不都在 Excel 里。更多时候它是微信里转来的一段消息、
 * 会议纪要里的一串人、群里接龙的一堆行、从网页上拖蓝复制下来的几行。
 * 这条路把那段文本交给模型切成行和列，**从第二步「对列」开始走的就是
 * 和文件导入同一条管线**——复核、预览、落库、撤销一个字都不用改。
 *
 * ## 模型只做一件事：切分
 *
 * 不做整理、不做翻译、不做推断、不做日期换算。每一格必须是原文里原样出现过的字。
 * 这个约束不是为了让提示词好写，是为了让它**可核对**：
 * 既然每一格都该在原文里找得到，那么找不到的那一格就是模型编的，
 * 下面 `核对` 里那一句 `原文.includes(格)` 就是一条能跑的断言。
 *
 * 换算留给下游：`认日期` 认得「2026年9月19日」，`规整手机号` 认得「138 0000 1111」，
 * `认枚举` 认得跟进状态——它们都是纯函数、都有测试、都不会看心情。
 * 让模型去做同一件事，等于把三个有测试的函数换成一个没有测试的。
 *
 * ## 两条核对，防的是两种相反的错
 *
 *   - **编出来的**：原文里没有这个人、没有这个号，模型补齐了一个像样的。
 *     这是最危险的一种——假客户混进库里，看不出来，还会被打电话。
 *   - **漏掉的**：原文里有十五个人，模型只给了九个。
 *     这是最安静的一种，和「没对上的列静默丢掉」是同一种病。
 *
 * 两条都只用原文本身判，不再问模型第二遍：让模型检查自己刚写的东西，
 * 它会说没问题。
 */
import { 列数上限 } from "./parse";

/** 一次最多粘多少字。够一份几十人的名单或一段几十条的聊天记录 */
export const 粘贴字数上限 = 6000;
/** 模型最多能切出多少行。再多就该回去存成 Excel 走文件那条路 */
export const 粘贴行数上限 = 200;
/** 单个格子最多留多少字。备注列在聊天记录上最容易长成一整段 */
export const 单格上限 = 500;

/** 全角转半角。微信和网页上复制下来的号码里全角数字是常事 */
function 半角(s: string): string {
  return s.replace(/[！-～]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0));
}

/**
 * 比对用的规整：全角转半角、去空白、去常见标点、转小写。
 *
 * **两边都规整，所以只会让比对更宽松，不会更严。** 方向是刻意的：
 * 这条核对的目的是抓住「模型编了一个原文里没有的号码」，
 * 不是抓住「模型把括号抄丢了」。宁可漏报一次抄写走样，不可误报一次
 * ——误报会让人学会忽略这条提示，那它就等于不存在了。
 */
export function 规整比对(s: string): string {
  return 半角(s)
    .replace(/[\s　]/g, "")
    .replace(/[-_/\\|.,、，。:：;；'"`()（）\[\]【】<>《》*#+~!?！？]/g, "")
    .toLowerCase();
}

/**
 * 把文本里长得像手机号的抠出来，规整成 11 位。
 *
 * **只认大陆手机号，不认座机、不认海外号。** 和 `像手机号` 那条刻意放松的规矩
 * 反着来，因为这两个函数干的事不一样：那条管的是「这一格能不能进库」，
 * 放松是为了不把人真实的客户挡在外面；这条管的是「模型有没有漏人」，
 * 放松只会让身份证号、金额、订单号都被当成人，于是每导一次都弹一条假警报。
 * **假警报比没有警报更糟**：人学会了忽略它。所以这条一路宁可漏报，不可误报。
 *
 * 难处只有一个：`138 0000 1111` 中间那两个空格要抹掉才认得出，而
 * `2026-09-19 13800001111` 里日期和号码中间那个空格抹掉就粘成了一串假数字。
 * 同样是一个空格，看不出哪个该抹。
 *
 * 办法是先按「数字 + 中间的空格横线」切成一段一段，再分两次看：
 * 整段恰好 11 位就是它（`138 0000 1111`）；位数对不上说明这一段里不止一个数，
 * 那就拆开每一截单独看（`2026-09-19 13800001111` 拆出四截，只有最后一截像号码）。
 * 两次都认不出来就认了——漏报一个号码只是这张网少一个眼，
 * 而误报一次会让整张网失去信用。
 */
export function 抽手机号(text: string): string[] {
  const out = new Set<string>();
  for (const m of 半角(text).matchAll(/\d[\d \t\-]*\d/g)) {
    const 整 = 认号(m[0]);
    if (整) {
      out.add(整);
      continue;
    }
    // 位数对不上说明这一段里不止一个数，拆开每一截单独看
    for (const 片 of m[0].split(/[ \t\-]+/)) {
      const n = 认号(片);
      if (n) out.add(n);
    }
  }
  return [...out];
}

/**
 * 一段数字是不是一个大陆手机号，是就返回规整后的 11 位。
 *
 * 国家码要脱掉：微信名片和通讯录导出里 `+86 138 0000 1111` 是常态，
 * 不脱的话整段是 13 位、拆开又拆成四截，两条路都认不出来——
 * 而那明明就是表里第一个人。脱的规矩和 `规整手机号` 那条一致，
 * 两处认的必须是同一个号，否则这张网会在「原文里有、表里没有」上乱报。
 */
function 认号(片: string): string | null {
  const s = 片.replace(/\D/g, "").replace(/^0*86(?=\d{11}$)/, "");
  return /^1[3-9]\d{9}$/.test(s) ? s : null;
}

/** 模型编出来的那一格：清空之后照原样报给人看 */
export type 编造格 = { 行号: number; 列名: string; 值: string };

export type 粘贴结果 = {
  表头: string[];
  数据: string[][];
  /** 原文里找不到、已经被清空的格子 */
  编造: 编造格[];
  /** 原文里有、整张表里却没出现的手机号 */
  漏掉: string[];
  /** 超出上限被切掉的部分，和文件那条路共用同一个提示条 */
  截断了?: { 行?: number; 列?: number };
};

/**
 * 给模型的话。
 *
 * 列名建议来自 `字段表`，所以业务配置改了叫法（「学员」改成「客户」、
 * 「院校」改成「公司」）这里跟着变——否则模型会给出一份表头，
 * 而下一步的 `猜列` 一列都对不上，人要手点十次。
 */
export function 组提示词(原文: string, 列名建议: readonly string[], 对象称呼: string): string {
  return `下面是一段没有格式的文本，里面有若干个${对象称呼}的信息。把它切成一张表格。

你只做一件事：**切分**。不整理、不翻译、不推断、不补全。

- 每一格必须是原文里**原样出现过的字**，一个字都不许改、不许添、不许猜。
- 原文没写的，那一格就是空字符串 ""。不要填「无」「未知」「暂无」「-」。
- 电话号码原样抄，连里面的空格和横线一起抄。不要补国家码，不要改写格式。
- 日期原样抄：「下周三」「10月20号」「明年春天」都原样抄，**不要换算成具体哪一天**。
- 一个人一行。同一个人在原文里被提到好几次，合成一行，不要出现两行。
- 表头用原文里的叫法；原文里没有表头时，从这些叫法里挑合适的：${列名建议.join("、")}。
- 原文里有、但放不进上面那些列的信息（微信号、地址、聊天里的一句要紧的话），
  放进「备注」列，原样抄，每格不超过 ${单格上限} 字。
- 最多 ${粘贴行数上限} 行、${列数上限} 列。

输出严格 JSON：{"表头": ["姓名", "手机号", "备注"], "数据": [["张三", "138 0000 1111", "群里接龙第 3 个"]]}
「数据」里每一行的长度必须和「表头」一样长。

原文：
"""
${原文}
"""`;
}

function 取字符串(v: unknown): string {
  if (typeof v === "string") return v.trim().slice(0, 单格上限);
  // 模型偶尔把号码当数字给回来。它会丢掉前导零，但那不是这里能补的，
  // 下面的核对会照常把它和原文比一遍
  if (typeof v === "number" && Number.isFinite(v)) return String(v);
  return "";
}

/**
 * 模型给的东西 → 能往下走的二维表，外加两份核对结果。
 *
 * **模型的输出一律当不可信输入**（和 ai-draft.ts 同一条）：形状不对就抛错，
 * 超限就切掉并说出来，编出来的格子清空并列出来。
 *
 * 表头不参与核对：表头是模型起的名字，本来就不必是原文里的字
 * （原文压根没有表头是常态），而它下一步就摆在人眼前让人改。
 * 真正要盯的是数据格——那些会进库、进了库就看不出来历的东西。
 */
export function 核对(raw: unknown, 原文: string): 粘贴结果 {
  const r = (raw ?? {}) as Record<string, unknown>;
  if (!Array.isArray(r.表头) || !Array.isArray(r.数据)) {
    throw new Error("AI 没有按格式返回表格，请重试");
  }

  const 原列数 = r.表头.length;
  const 表头 = r.表头.slice(0, 列数上限).map((h) => 取字符串(h));
  const 列数 = 表头.length;
  if (列数 === 0) throw new Error("AI 没能从这段文本里读出任何一列");

  const 全部行 = r.数据.filter((row): row is unknown[] => Array.isArray(row));
  const 收下 = 全部行.slice(0, 粘贴行数上限).map((row) => {
    const out = row.slice(0, 列数).map((c) => 取字符串(c));
    while (out.length < 列数) out.push("");
    return out;
  });

  const 源 = 规整比对(原文);
  const 编造: 编造格[] = [];
  const 数据 = 收下
    .map((row, i) => {
      const 行号 = i + 2; // 和文件那条路对齐：1 是表头
      return row.map((格, 列) => {
        const 紧 = 规整比对(格);
        if (!紧 || 源.includes(紧)) return 格;
        编造.push({ 行号, 列名: 表头[列] || `第 ${列 + 1} 列`, 值: 格 });
        return "";
      });
    })
    .filter((row) => row.some((c) => c !== ""));

  const 表里的号 = new Set(抽手机号(数据.map((r2) => r2.join(" ")).join("\n")));
  const 漏掉 = 抽手机号(原文).filter((n) => !表里的号.has(n));

  const 截断了: { 行?: number; 列?: number } = {};
  if (全部行.length > 粘贴行数上限) 截断了.行 = 全部行.length;
  if (原列数 > 列数上限) 截断了.列 = 原列数;

  return { 表头, 数据, 编造, 漏掉, ...(截断了.行 || 截断了.列 ? { 截断了 } : {}) };
}
