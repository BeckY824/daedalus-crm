/**
 * 当前页是什么，一句话。给全局 AI 面板当上下文用。
 *
 * **必须看得见、点得掉**：面板顶上把这句话摆出来，旁边一个 ×。
 * 用户得知道 AI 看到了什么——一个隐形的上下文，答歪了没人能解释为什么。
 *
 * 纯函数、不引 next：路由是字符串，测得起来。
 * 只认一级路由；客户详情页的名字由调用方补（那要查库，不是路径能知道的）。
 *
 * ---
 *
 * **每一页还要说清「这一页的数据用哪个工具查」。** 2026-09-19 报上来的：
 * 在线索页问「Steven 是哪家公司的？」，模型连着四次 `search_customers()` 空参数，
 * 一条都没查着就中断了——Steven 是那条线索的联系人，在 Lead 表里，
 * 而 `search_customers` 翻的是 Customer 表，两张表。
 *
 * `list_leads` 的工具说明里其实**已经**写着「线索和客户是两张表，别用 search_customers 找线索」，
 * 没用：十一个工具的说明一起摆在模型面前，它按名字的字面意思挑，「搜客户」看着最像「找人」。
 * 小模型在这一步上不可靠，所以不能只靠工具自己的说明——
 * 人正站在哪一页是我们**确定知道**的信息，把它兑换成一句指名道姓的话，
 * 比让模型每次重新推理一遍稳得多（和 agent/intents.ts 是同一个思路）。
 */
export type 页面上下文 = {
  /** 这一页叫什么，不带筛选。落库时当对话标题的前缀用 */
  名: string;
  /** 面板顶上那一行，给人看 */
  标签: string;
  /** 塞进提问里的那句，给模型看。空串 = 这一页没有值得带的上下文 */
  提示: string;
  /**
   * 这一页的范围，结构化的那份。给意图直连用：「明杰哥的电话」在渠道页上，
   * 明杰哥又正列在表里，那就直接 list_channels(keyword=明杰哥)，不问模型。
   * 只有登记了 `查一个` 的页面才有。
   */
  范围?: 页面范围;
};

export type 页面范围 = {
  /** 这一页那张表叫什么，给人看 */
  表: string;
  /** 查这一页上某一条记录该用的工具，和它收名字的那个参数 */
  工具: string;
  参数: string;
  /** 这一页上正列着的名字 */
  名字: string[];
};

type 页 = {
  名: string;
  提示: string;
  /**
   * 这一页的数据该用哪个工具查。
   * **加一页就必须填它**，否则那一页的面板会退回「凭工具名字猜」——
   * 不报错，只是像线索页那样连查四次空的。tests/ai-context-page.test.ts 会对一遍。
   */
  工具?: string;
  /** 光给工具名不够时补一句：这一页的东西在库里到底是什么 */
  提醒?: string;
  /**
   * 那个默认工具**答不了什么**，以及该换成谁。
   *
   * 2026-09-19 报上来的：在数据页问「新增的客户是谁？」答不出来。
   * 因为这一页指的是 `query_metric`，而它返回的是 `{metric, rows:[{label,value}]}`
   * ——**只有聚合数字，没有姓名也没有 id**，「是谁」它天生答不了。
   * 而指路那句原话还写着「别挑别的工具试」，等于把出路也堵死了。
   *
   * 那句话本来是为线索页写的（要点是「别用 search_customers 查线索表」），
   * 一刀切套到每一页就成了这个样子。默认工具不是万能的，答不了的要写明去哪儿。
   */
  补?: string;
  /**
   * 「查这一页上的某一条」怎么查：工具名 + 收名字的那个参数。
   * 有它，这一页的名字才会被带给模型，意图直连才认得「X 的电话」这种问法。
   * 没它的页（数据页、跟进记录页）名字带过去也没有一个能按名字查的工具，不如不带。
   */
  查一个?: { 工具: string; 参数: string };
};

