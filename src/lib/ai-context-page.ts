/**
 * 「这一页的数据先用 X 查」那一句。没登记工具的页面（设置、用量）不说。
 *
 * **指的是起点，不是唯一出路。** 原话是「问到这一页上的名字、记录、数字，
 * 先用它，别挑别的工具试」——在线索页那是对的（要挡的正是「拿 search_customers
 * 去查线索表」），可一刀切到数据页就成了死路：那一页指的是 query_metric，
 * 而它只给数不给名单，「新增的客户是谁」它天生答不了，后半句还不让换。
 * 所以现在写明「它答不了的就换」，范围（这一页说的那个）照旧要守。
 */
function 指路(p: 页): string {
  if (!p.工具) return "";
  return (
    `\n  这一页的数据先用 **${p.工具}** 查。${p.提醒 ?? ""}${p.补 ?? ""}` +
    `它答不了的（要具体是谁、要别的表、要排序），换一个合适的工具——但范围仍然是这一页说的这个。`
  );
}

/**
 * @param pathname 形如 /customers 或 /customers/abc123
 * @param params   地址栏参数
 * @param 详情名   详情页上这条记录叫什么（客户姓名等）。列表页传 null
 */
export function 认页面(pathname: string, params: URLSearchParams | null, 详情名?: string | null, 可见行?: readonly string[]): 页面上下文 | null {
  const 命中 = 一级[pathname];
  if (命中) {
    const 条件: string[] = [];
    for (const [k, 说法] of Object.entries(筛选说法)) {
      const v = params?.get(k);
      if (v) 条件.push(`${说法} ${v}`);
    }
    if (!命中.提示 && 条件.length === 0) return null; // 首页、设置这些：没什么可带的
    const 尾 = 条件.length ? `，筛了${条件.join("、")}` : "";
    /*
      这一页上正列着的名字。**这是上下文里最值钱的一句**：有了它，
      「明杰哥在哪张表」不再是模型要猜的事——他就在这一页上，这一页就是渠道表。
      只在登记了 查一个 的页面带（带了也得有工具能按名字查才有用），最多 50 个。
    */
    const 名字 = 命中.查一个 ? (可见行 ?? []).slice(0, 50) : [];
    const 列着 = 名字.length
      ? `\n  这一页上现在列着：${名字.join("、")}。**这些名字都是${命中.名}表里的记录**，问到其中任何一个，直接用 ${命中.查一个!.工具}（${命中.查一个!.参数}=那个名字）查，不要去别的表找。`
      : "";
    return {
      名: 命中.名,
      标签: `${命中.名}${尾}`,
      提示: `${命中.提示 || `用户正在看${命中.名}`}${尾}。回答时把这个范围考虑进去。${指路(命中)}${列着}`,
      ...(命中.查一个 ? { 范围: { 表: 命中.名, 工具: 命中.查一个.工具, 参数: 命中.查一个.参数, 名字 } } : {}),
    };
  }
  // 客户详情 /customers/xxx
  const m = /^\/customers\/([^/]+)$/.exec(pathname);
  if (m && 详情名)
    return {
      名: `客户 · ${详情名}`,
      标签: `客户 · ${详情名}`,
      提示:
        `用户正在看${详情名}的记录页。「他」「这位」指的就是${详情名}。` +
        `\n  这一页的数据用 **get_customer** 查（参数 name="${详情名}"）。问到这位的情况先用它。`,
    };
  return null;
}
