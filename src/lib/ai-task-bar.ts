"use client";

/**
 * 侧栏底部那条「AI 任务」显示成什么。
 *
 * **从一张常驻的单子改成一条完成通知（2026-09-19）。** 原来是左下角一个方块列表，
 * 最多四行，每行一个任务，答完了还得人点一下才消失——于是它一直占着地方，
 * 而人真正想知道的只有一件事：我刚才问的那句，答完了没有。
 * codex / Claude Code 的做法是分层：跑的时候给一条细进度，跑完叫你一声，然后自己走。
 * 这里照那个路子：
 *
 *   跑着的   一条细进度条 + 一行字。说不出百分比就别装（和更新药丸的 idle 一样来回扫）
 *   答完了   变成「答完了」，**3 秒后自己淡出**，不用人点
 *   要你做事 失败、或者答完但里面有建议卡等着确认——留着，它不会自己走
 *
 * 同时有好几条就只显示一条，后面缀「+N」：左下角那点地方不是收件箱，
 * 真要翻，首页那条对话列表本来就在。
 *
 * 逻辑抽在这儿而不是写在组件里：挑哪一条、什么时候自己走、叫人的时候说什么，
 * 这三件是规矩，规矩测得出来；写进 JSX 就只能靠眼睛看。
 */

export type 快照项 = {
  key: string;
  status: "loading" | "done" | "error";
  标签: { 名: string; 去?: string };
  有建议: boolean;
};

export type 任务条 = {
  key: string;
  名: string;
  去?: string;
  /**
   * 跑着 = 还在想；失败、待确认 = 要人做事的，不会自己走；答完 = 3 秒后自己淡出。
   * 分四种而不是「跑着 / 要你 / 答完」三种：失败和待确认虽然都得留着，
   * 但一个是红的、一个是等人点，图标和颜色不一样，合成一种样式表就得去猜说明文字。
   */
  态: "跑着" | "失败" | "待确认" | "答完";
  /** 右边那一行小字 */
  说明: string;
  /** 同时还有几条（不含这一条）。0 就不显示 */
  还有: number;
};

/** 答完之后留多久自己走。够看清那一行字，又不至于杵在那儿 */
export const 自动消毫秒 = 3000;

/**
 * 这一屏只显示一条，挑哪一条。
 *
 * 顺序就是紧要程度：还在跑的最要紧（人在等它）→ 要人做事的（失败 / 待确认）
 * → 只是答完了的（看一眼就行，它自己会走）。
 */
export function 挑一条(任务: 快照项[]): 任务条 | null {
  const 跑着 = 任务.filter((t) => t.status === "loading");
  if (跑着.length) return 成条(跑着[0], "跑着", 跑着.length - 1);

  const 失败 = 任务.filter((t) => t.status === "error");
  if (失败.length) return 成条(失败[0], "失败", 失败.length - 1);

  const 待确认 = 任务.filter((t) => t.status === "done" && t.有建议);
  if (待确认.length) return 成条(待确认[0], "待确认", 待确认.length - 1);

  const 答完 = 任务.filter((t) => t.status === "done");
  if (答完.length) return 成条(答完[0], "答完", 答完.length - 1);

  return null;
}

/** 一行小字。四种态各一句，别处不许再另写一版 */
const 说明: Record<任务条["态"], string> = {
  跑着: "正在想…",
  失败: "没答上来",
  待确认: "等你确认",
  答完: "答完了",
};

/** 样式表里的类名。中文类名在 CSS 里不好写，这里定死一份对照 */
export const 类名: Record<任务条["态"], string> = {
  跑着: "loading",
  失败: "error",
  待确认: "wait",
  答完: "done",
};

function 成条(t: 快照项, 态: 任务条["态"], 还有: number): 任务条 {
  return { key: t.key, 名: t.标签.名, 去: t.标签.去, 态, 说明: 说明[态], 还有 };
}

/**
 * 这一条会不会自己走。
 *
 * **只有「单纯答完」会。** 失败要人知道；带建议卡的那条是在等人点确认，
 * 自己淡掉就等于把一件没做完的事悄悄抹了。
 */
export function 该自动消(t: 快照项): boolean {
  return t.status === "done" && !t.有建议;
}

/**
 * 跑完了叫人一声时说什么。还在跑就没什么可说的（返回 null）。
 *
 * 只在桌面端、且窗口不在前台时才会真的弹出来——在前台的时候侧栏那一条就够了，
 * 再弹一个系统通知是吵。前台与否由壳判断（desktop/main.js 的 notify:show）。
 */
export function 通知文案(t: 快照项): { 标题: string; 正文: string } | null {
  if (t.status === "loading") return null;
  if (t.status === "error") return { 标题: "没答上来", 正文: t.标签.名 };
  if (t.有建议) return { 标题: "答完了，有一条等你确认", 正文: t.标签.名 };
  return { 标题: "答完了", 正文: t.标签.名 };
}
